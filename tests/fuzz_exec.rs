struct St<'a> {
    prog: &'a Prog,
    vars: Vec<i64>,
    /// `main`'s array and struct. Empty inside a function, which cannot name
    /// them, and in a program that declares neither.
    arr: Vec<i64>,
    fields: Vec<i64>,
    /// The struct's array field. `main`'s, like `arr` — a function reaches the
    /// struct through a by-reference parameter, and indexing the field there
    /// is not something the compiler emits.
    afield: Vec<i64>,
    /// The struct nested inside the struct, `main`'s like the others. Read
    /// through `s.n.g{j}` and travels with the struct.
    nested: Vec<i64>,
    /// The variant `main`'s enum holds, or the one handed to a callee. `None`
    /// where no enum is in scope, which is what makes naming one there a bug
    /// in the generator rather than a silent zero.
    tag: Option<usize>,
    /// The active variant's `u8` payload, when the enum in scope carries one.
    /// `None` for a unit variant or no enum — naming a payload there is a
    /// generator bug rather than a silent zero.
    epay: Option<i64>,
    /// The length of the string in scope, on the same rule as `tag`.
    strlen: Option<usize>,
    counters: Vec<i64>,
    loops: Vec<i64>,
    /// The function being executed and its remaining budget, for a self-call.
    /// `None` in `main`, where no self-call can appear.
    current: Option<(usize, i64)>,
    /// Which function `DEV.call` currently holds, by id. Program state,
    /// written by `S::Install` — the whole point of dispatching through a
    /// pointer is that this is not a property of the source.
    dev: usize,
    /// Which of `main`'s variables the pointer currently names. `None` where
    /// there is no pointer in scope, which is what makes naming one there a
    /// generator bug rather than a silent zero.
    ptr: Option<PtrTarget>,
    /// Each slice's current `(start, len)` into `TBL`. Program state too:
    /// `Reslice` and `CopySlice` move it. Empty inside a function, which names
    /// no slice.
    slices: Vec<(usize, usize)>,
    /// The mutable `static`'s current value, `None` where none is in scope.
    /// `S::GStore` writes it; `E::GLoad` reads it.
    gstatic: Option<i64>,
}

/// Call a generated function. Its locals are fresh per invocation — which is
/// what the compiler's frame save/restore has to reproduce across a recursive
/// call — and it reads nothing but its own scope, so no caller state is passed.
#[allow(clippy::too_many_arguments)]
fn call_fn(
    p: &Prog,
    id: usize,
    budget: i64,
    args: &[i64],
    slice: Option<(usize, usize)>,
    fields: &[i64],
    afield: &[i64],
    nested: &[i64],
    tag: Option<usize>,
    strlen: Option<usize>,
    ty: Ty,
) -> i64 {
    let f = &p.funcs[id];
    // Arguments arrive already narrowed to the *parameter's* type — the caller
    // widened at the boundary if it had to — and each local is at its own.
    let mut vars: Vec<i64> = args.to_vec();
    vars.extend(
        f.local_init
            .iter()
            .zip(f.var_types[f.params..].iter())
            .map(|(v, t)| narrow(*v, *t)),
    );
    let mut st = St {
        prog: p,
        vars,
        // A function names no array and no table — those stay `main`'s. The
        // struct is different: it is passed by *address*, so the callee reads
        // the caller's own fields and the values carry in unchanged. Nothing
        // writes them through the parameter, which is what keeps this a copy
        // of the values rather than an aliasing model.
        arr: Vec::new(),
        fields: fields.to_vec(),
        // The array field travels with them: it is part of the same bytes, and
        // `xp.a[i]` reads it through the same pointer.
        afield: afield.to_vec(),
        // The nested struct's fields travel with the struct exactly as the
        // array field does: they are part of the same bytes, read through the
        // parameter as `xp.n.g{j}`. Nothing writes them there, so the values
        // carry in unchanged — a copy, not an alias.
        nested: nested.to_vec(),
        // The tag, when this function takes the enum. A unit enum's value is
        // its variant index, so nothing else has to travel.
        tag,
        // The function never `match`es the enum — that read is `main` only —
        // so no payload travels with it.
        epay: None,
        // The string's length, for the same reason: reads stay at `.len`.
        strlen,
        // Function bodies contain no loops, so these are never indexed; sized
        // rather than empty so a generator change cannot panic here.
        counters: p.counters.iter().map(|c| *c as i64).collect(),
        loops: vec![0; p.loops],
        current: Some((id, budget)),
        // A function body contains no indirect call, so this is never read.
        dev: 0,
        // No pointer either: it is `main`'s local, like the array.
        ptr: None,
        // The parameter, when this function takes one — the only slice its
        // body can name, and the one `sp` resolves to.
        slices: slice.into_iter().collect(),
        // A function body cannot name `main`'s static, like the pointer above.
        gstatic: None,
    };
    let _ = ty; // the caller's type; a callee works entirely at its own
    if f.recursive && budget == 0 {
        return eval(&f.base, &st, f.ret_ty);
    }
    exec(&f.body, &mut st, f.ret_ty);
    eval(&f.ret, &st, f.ret_ty)
}

/// Apply a binary operator to two already-evaluated operands, at the operator's
/// type. The one place the language's arithmetic lives, so [`eval`] and
/// [`const_fold`] cannot drift from each other.
fn apply_bin(a: i64, op: Op, b: i64, ty: Ty) -> i64 {
    let v = match op {
        Op::Add => a.wrapping_add(b),
        Op::Sub => a.wrapping_sub(b),
        Op::Mul => a.wrapping_mul(b),
        // `x / 0` and `x % 0` are the all-ones value of the type — defined, not
        // undefined, so a divisor that is only zero *sometimes* needs no
        // avoiding. `narrow` turns -1 into 0xFF or 0xFFFF for the unsigned
        // halves of the pair.
        //
        // `i8::MIN / -1` overflows and is *also* defined: every arithmetic
        // operator wraps, and `narrow(128, i8)` is -128, which is what the
        // compiler produces.
        Op::Div => {
            if b == 0 {
                -1
            } else {
                a.wrapping_div(b)
            }
        }
        Op::Rem => {
            if b == 0 {
                -1
            } else {
                a.wrapping_rem(b)
            }
        }
        // Bitwise operators act on the value's bit pattern, so a negative
        // operand has to be seen unsigned first.
        Op::And => (raw(a, ty) & raw(b, ty)) as i64,
        Op::Or => (raw(a, ty) | raw(b, ty)) as i64,
        Op::Xor => (raw(a, ty) ^ raw(b, ty)) as i64,
        Op::Shl => a << b.clamp(0, ty.bits() as i64 - 1),
        // `>>` on a signed type is arithmetic, which is what Rust's `>>` on
        // `i64` already does for our sign-correct values.
        Op::Shr => a >> b.clamp(0, ty.bits() as i64 - 1),
    };
    narrow(v, ty)
}

/// The value of `e` if the compiler can fold it to a constant, mirroring the
/// arithmetic subset the compiler's own const-evaluator sees: literals and
/// operators over literals, with casts. Any node that reads run-time state —
/// a variable, an element, a call, a pointer — makes the whole expression
/// non-constant and yields `None`.
///
/// Its one use is keeping a *divisor* from being a constant the compiler can
/// prove is zero. A run-time-zero divisor is defined (the all-ones sentinel);
/// a compile-time-zero one is a hard error the oracle would misread as a
/// miscompile. Anchoring is meant to keep a divisor non-constant, but where its
/// type has no run-time value in scope it degrades to literals — `(-19) / 27`
/// folds to 0 — so the divisor site checks this and repairs it.
fn const_fold(e: &E, ty: Ty) -> Option<i64> {
    match e {
        E::Lit(v) => Some(narrow(*v, ty)),
        E::Cast(to, inner) => Some(narrow(narrow(const_fold(inner, ty)?, *to), ty)),
        E::At(from, inner) => Some(narrow(const_fold(inner, *from)?, ty)),
        E::Bin(l, op, r) => Some(apply_bin(const_fold(l, ty)?, *op, const_fold(r, ty)?, ty)),
        _ => None,
    }
}

fn eval(e: &E, st: &St, ty: Ty) -> i64 {
    match e {
        E::Lit(v) => narrow(*v, ty),
        E::Var(i) => st.vars[*i],
        E::Loop(id) => narrow(st.loops[*id], ty),
        E::Cast(to, inner) => narrow(narrow(eval(inner, st, ty), *to), ty),
        // The arithmetic happened at `from`; any extension is after it.
        E::At(from, inner) => narrow(eval(inner, st, *from), ty),
        E::Call {
            id,
            budget,
            args,
            slice_arg,
            struct_arg,
            enum_arg,
            str_arg,
        } => {
            // Each argument at its *parameter's* type, not at the type of the
            // expression the call sits inside. The two are the same only in a
            // program of one width: elsewhere a `u8` context would truncate a
            // value the machine hands over whole.
            let vals: Vec<i64> = args
                .iter()
                .zip(st.prog.funcs[*id].var_types.iter())
                .map(|(a, pt)| eval(a, st, *pt))
                .collect();
            let sl = slice_arg.map(|k| st.slices[k]);
            let fl: &[i64] = if *struct_arg { &st.fields } else { &[] };
            let af: &[i64] = if *struct_arg { &st.afield } else { &[] };
            let nf: &[i64] = if *struct_arg { &st.nested } else { &[] };
            let tg = if *enum_arg { st.tag } else { None };
            let sn = if *str_arg { st.strlen } else { None };
            narrow(
                call_fn(
                    st.prog,
                    *id,
                    budget.unwrap_or(0) as i64,
                    &vals,
                    sl,
                    fl,
                    af,
                    nf,
                    tg,
                    sn,
                    ty,
                ),
                ty,
            )
        }
        E::SelfCall(arg) => {
            let (id, budget) = st.current.expect("a self-call outside a function");
            let v = eval(arg, st, st.prog.funcs[id].var_types[0]);
            // The slice travels down the recursion unchanged: the self-call
            // passes `sp` along, so the callee sees what this frame sees.
            let sl = st.slices.first().copied();
            // The struct travels down the recursion the same way `sp` does:
            // the self-call passes `xp` along, so the callee sees this frame's.
            narrow(
                call_fn(
                    st.prog,
                    id,
                    budget - 1,
                    &[v],
                    sl,
                    &st.fields,
                    &st.afield,
                    &st.nested,
                    st.tag,
                    st.strlen,
                    ty,
                ),
                ty,
            )
        }
        E::MutualCall(partner, arg) => {
            let (_, budget) = st.current.expect("a mutual call outside a function");
            let v = eval(arg, st, st.prog.funcs[*partner].var_types[0]);
            // The partner takes no slice — a pair member never carries one, so
            // there is nothing to pass along.
            narrow(
                call_fn(
                    st.prog,
                    *partner,
                    budget - 1,
                    &[v],
                    None,
                    &[],
                    &[],
                    &[],
                    None,
                    None,
                    ty,
                ),
                ty,
            )
        }
        E::Dispatch { sel, arg } => {
            let k = match sel {
                Sel::Lit(k) => *k,
                Sel::Wrapped(i) => (raw(st.vars[*i], ty) as u8 as usize) % st.prog.vtable,
            };
            let callee = st.prog.candidate(k);
            let v = eval(arg, st, st.prog.funcs[callee].var_types[0]);
            narrow(
                call_fn(
                    st.prog,
                    callee,
                    0,
                    &[v],
                    None,
                    &[],
                    &[],
                    &[],
                    None,
                    None,
                    ty,
                ),
                ty,
            )
        }
        E::DevCall(arg) => {
            let v = eval(arg, st, st.prog.funcs[st.dev].var_types[0]);
            narrow(
                call_fn(
                    st.prog,
                    st.dev,
                    0,
                    &[v],
                    None,
                    &[],
                    &[],
                    &[],
                    None,
                    None,
                    ty,
                ),
                ty,
            )
        }
        E::Elem(ix) => st.arr[eval_index(ix, st, ty)],
        E::Konst(ix) => narrow(st.prog.konst[eval_index(ix, st, ty)], ty),
        E::SliceElem(i, ix) => {
            let (start, len) = st.slices[*i];
            narrow(st.prog.konst[start + eval_index_mod(ix, st, ty, len)], ty)
        }
        E::SliceLen(i) => narrow(st.slices[*i].1 as i64, ty),
        // The pointer names one of `main`'s variables; which one is whatever
        // the last `Repoint` left. A read is at the *pointee's* type, which is
        // the pointer's own, and then narrowed to the context like any other
        // storage read.
        E::PtrLoad | E::PtrPtrLoad => {
            let t = st.ptr.as_ref().expect("a pointer read needs a pointer");
            narrow(
                match t {
                    PtrTarget::Var(k) => st.vars[*k],
                    PtrTarget::Field(k) => st.fields[*k],
                    PtrTarget::Elem(k) => st.arr[*k],
                },
                ty,
            )
        }
        E::Field(i) => st.fields[*i],
        E::NestedField(j) => st.nested[*j],
        E::AField(ix) => st.afield[eval_index_mod(ix, st, ty, AFLEN)],
        // `(e as T)` is the variant index at `T`. Reaching this with no tag
        // would mean the generator named an enum no scope has.
        E::EnumVal => narrow(
            st.tag.expect("an enum read with no enum in scope") as i64,
            ty,
        ),
        E::EnumMatch => {
            // The unit variant yields the constant its arm spells; a payload
            // variant binds `x` and yields `(x as T)`, which is the payload
            // narrowed to the context type.
            let tag = st.tag.expect("an enum match with no enum in scope");
            if tag == 0 {
                narrow(0, ty)
            } else {
                narrow(
                    st.epay.expect("a payload variant with no payload in scope"),
                    ty,
                )
            }
        }
        E::StrLen => narrow(
            st.strlen.expect("a string read with no string in scope") as i64,
            ty,
        ),
        E::StrIndex(ix) => {
            // The string is `main`'s immutable literal, so the byte is a fact
            // about it, not aliased state: read it straight from STRINGS. The
            // modulus is the literal's own length — a short string has fewer
            // than ALEN bytes — and the byte is always ASCII, so it fits every
            // signed type without a sign question.
            let k = st
                .prog
                .str_init
                .expect("a string indexed with no string in scope");
            let bytes = STRINGS[k].as_bytes();
            let idx = eval_index_mod(ix, st, ty, bytes.len());
            narrow(bytes[idx] as i64, ty)
        }
        E::GLoad => st.gstatic.expect("a static read with no static in scope"),
        E::Bin(l, op, r) => {
            let a = eval(l, st, ty);
            let b = eval(r, st, ty);
            apply_bin(a, *op, b, ty)
        }
    }
}

/// Where an index lands. Mirrors the three forms the generator emits, each of
/// which is in range by construction.
fn eval_index(ix: &Ix, st: &St, ty: Ty) -> usize {
    eval_index_mod(ix, st, ty, ALEN)
}

/// As [`eval_index`], against a length known only at run time. A slice's is
/// whatever the last `Reslice` or `CopySlice` left, so the modulus the source
/// spells is `sl{i}.len` rather than a constant.
fn eval_index_mod(ix: &Ix, st: &St, ty: Ty, len: usize) -> usize {
    match ix {
        Ix::Lit(k) => *k,
        Ix::Loop(id) => st.loops[*id] as usize,
        // `(v as u8) % LEN`: the cast keeps the low byte, whatever the type.
        Ix::Wrapped(i) => (raw(st.vars[*i], ty) as usize & 0xFF) % len,
    }
}

/// A condition needs no context type: each comparison carries the type its two
/// sides were generated at, which is not the type of the statement around it.
fn eval_bool(b: &B, st: &St) -> bool {
    match b {
        // Both sides at the type the generator compared them at, which is not
        // necessarily the type of the statement around them.
        B::Rel(at, l, c, r) => c.apply(eval(l, st, *at), eval(r, st, *at)),
        B::And(l, r) => eval_bool(l, st) && eval_bool(r, st),
        B::Or(l, r) => eval_bool(l, st) || eval_bool(r, st),
        B::Not(inner) => !eval_bool(inner, st),
    }
}

fn exec(stmts: &[S], st: &mut St, ty: Ty) {
    for s in stmts {
        match s {
            S::Assign(place, want, e) => {
                // The destination's width, not the statement's: a narrow value
                // stored into a wide slot is widened by the language, and the
                // expression's own `Widen` node has already said where the
                // arithmetic happened.
                let value = eval(e, st, *want);
                match place {
                    Place::Var(v) => st.vars[*v] = value,
                    Place::Elem(ix) => {
                        let k = eval_index(ix, st, ty);
                        st.arr[k] = value;
                    }
                    Place::Field(f) => st.fields[*f] = value,
                    Place::AField(ix) => {
                        let k = eval_index_mod(ix, st, ty, AFLEN);
                        st.afield[k] = value;
                    }
                }
            }
            S::Install(id) => st.dev = *id,
            S::CopySlice(d, src) => st.slices[*d] = st.slices[*src],
            S::CopyRange { dst, src, len } => {
                for i in 0..*len {
                    st.arr[dst + i] = st.prog.konst[src + i];
                }
            }
            S::Reslice(i, start, len) => st.slices[*i] = (*start, *len),
            S::SliceFromCall(i, k) => st.slices[*i] = st.prog.mk_ranges[*k],
            // Both halves of the alias. The store lands in whichever variable
            // the pointer names *now*, and at the pointer's own type — every
            // target has it, so there is no widening to get wrong.
            S::PtrStore(t, e) | S::PtrPtrStore(t, e) => {
                let v = narrow(eval(e, st, *t), *t);
                match st.ptr.clone().expect("a pointer store needs a target") {
                    PtrTarget::Var(k) => st.vars[k] = v,
                    PtrTarget::Field(k) => st.fields[k] = v,
                    PtrTarget::Elem(k) => st.arr[k] = v,
                }
            }
            S::Repoint(k) => st.ptr = Some(k.clone()),
            // The argument is evaluated before the call, so the field it may
            // read is the one from *before* the write — which is the order the
            // machine runs it in too.
            S::PokeStruct(dst, e) => {
                let (w, r) = st.prog.poke.expect("a poke needs a `pk`");
                let base = st.prog.base;
                let v = narrow(eval(e, st, base), base);
                let back = st.fields[r];
                st.fields[w] = v;
                st.vars[*dst] = narrow(back, st.prog.var_types[*dst]);
            }
            S::PokePtr(target, dst, e) => {
                let base = st.prog.base;
                let add = narrow(eval(e, st, base), base);
                let new = narrow(st.vars[*target] + add, base);
                st.vars[*target] = new;
                st.vars[*dst] = new;
            }
            S::StructFromCall(k) => {
                let (fs, a, n) = &st.prog.mks[*k];
                st.fields = fs.iter().map(|v| narrow(*v, ty)).collect();
                st.afield = a.iter().map(|v| narrow(*v, ty)).collect();
                st.nested = n.iter().map(|v| narrow(*v, ty)).collect();
            }
            S::If(c, then, otherwise) => {
                if eval_bool(c, st) {
                    exec(then, st, ty);
                } else if let Some(e) = otherwise {
                    exec(e, st, ty);
                }
            }
            S::For(id, count, body) => {
                for i in 0..*count as i64 {
                    st.loops[*id] = i;
                    exec(body, st, ty);
                }
            }
            S::While(id, body) => {
                while st.counters[*id] > 0 {
                    exec(body, st, ty);
                    st.counters[*id] -= 1;
                }
            }
            // The static's own type is `base`, and `GStore` only appears in
            // `main`, where `ty` is `base` — so the value is computed and stored
            // at the static's width.
            S::GStore(e) => {
                let base = st.prog.base;
                st.gstatic = Some(narrow(eval(e, st, base), base));
            }
            // First matching arm wins, exactly as the compiler compares in
            // order; the value and every pattern are narrowed to the base type,
            // so the comparison uses that type's signed/unsigned ordering.
            S::IntMatch {
                scrut,
                arms,
                default,
            } => {
                let base = st.prog.base;
                let s = narrow(eval(scrut, st, base), base);
                let taken = arms.iter().find(|(p, _)| match p {
                    MatchPat::Lit(v) => s == narrow(*v, base),
                    MatchPat::Range(lo, hi, incl) => {
                        let (lo, hi) = (narrow(*lo, base), narrow(*hi, base));
                        s >= lo && if *incl { s <= hi } else { s < hi }
                    }
                });
                match taken {
                    Some((_, body)) => exec(body, st, ty),
                    None => exec(default, st, ty),
                }
            }
        }
    }
}

/// The final bit pattern of every program variable.
fn expected(p: &Prog) -> Vec<u32> {
    let at_base = |xs: &[i64]| -> Vec<i64> { xs.iter().map(|v| narrow(*v, p.base)).collect() };
    let mut st = St {
        prog: p,
        vars: p
            .init
            .iter()
            .zip(p.var_types.iter())
            .map(|(v, t)| narrow(*v, *t))
            .collect(),
        tag: p.enum_init,
        epay: match p.enum_init {
            // Already at the payload's declared type, so a wide payload carries
            // its full two-byte value and a `u8` one its byte.
            Some(k) if k > 0 => Some(p.enum_payload),
            _ => None,
        },
        strlen: p.str_init.map(|k| STRINGS[k].len()),
        arr: if p.aggregates {
            at_base(&p.arr_init)
        } else {
            Vec::new()
        },
        fields: match (p.aggregates, p.struct_init_from_call) {
            (false, _) => Vec::new(),
            (true, Some(k)) => at_base(&p.mks[k].0),
            (true, None) => at_base(&p.field_init),
        },
        afield: match (p.aggregates, p.struct_init_from_call) {
            (false, _) => Vec::new(),
            (true, Some(k)) => at_base(&p.mks[k].1),
            (true, None) => at_base(&p.afield_init),
        },
        nested: match (p.aggregates, p.struct_init_from_call) {
            (false, _) => Vec::new(),
            (true, Some(k)) => at_base(&p.mks[k].2),
            (true, None) => at_base(&p.nested_init),
        },
        counters: p.counters.iter().map(|c| *c as i64).collect(),
        loops: vec![0; p.loops],
        current: None,
        // The declaration installs the table's first entry.
        dev: if p.vtable > 0 { p.candidate(0) } else { 0 },
        ptr: p.ptr.as_ref().map(|(_, k)| k.clone()),
        slices: p.slices.clone(),
        gstatic: p.mut_static.map(|v| narrow(v, p.base)),
    };
    exec(&p.stmts, &mut st, p.base);
    // Each slice reports its first element and its length — the two halves of
    // the descriptor, so a copy that moves one and not the other shows up here
    // even in a program whose expressions never happened to read it.
    let descriptors: Vec<i64> = st
        .slices
        .iter()
        .flat_map(|(start, len)| [narrow(p.konst[*start], p.base), narrow(*len as i64, p.base)])
        .collect();
    // The mutable static reports its final value as the last cell, after the
    // descriptors — the same position `cell_types` and the rendered stores use.
    let gstatic: Vec<i64> = st.gstatic.into_iter().collect();
    // Each cell at its own width, which is no longer one number per program.
    st.vars
        .iter()
        .chain(st.arr.iter())
        .chain(st.fields.iter())
        .chain(st.afield.iter())
        .chain(st.nested.iter())
        .chain(descriptors.iter())
        .chain(gstatic.iter())
        .zip(cell_types(p))
        .map(|(v, t)| raw(*v, t))
        .collect()
}

/// The type of every reported cell, in the order `expected` produces them.
fn cell_types(p: &Prog) -> Vec<Ty> {
    let mut out: Vec<Ty> = p.var_types.to_vec();
    if p.aggregates {
        out.extend(std::iter::repeat_n(p.base, ALEN + SFIELDS + AFLEN + NESTED));
    }
    out.extend(std::iter::repeat_n(p.base, 2 * p.slices.len()));
    if p.mut_static.is_some() {
        out.push(p.base);
    }
    out
}

