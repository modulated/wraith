#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Ty {
    U8,
    U16,
    I8,
    I16,
}

const TYPES: [Ty; 4] = [Ty::U8, Ty::U16, Ty::I8, Ty::I16];

impl Ty {
    fn name(self) -> &'static str {
        match self {
            Ty::U8 => "u8",
            Ty::U16 => "u16",
            Ty::I8 => "i8",
            Ty::I16 => "i16",
        }
    }
    fn bits(self) -> u32 {
        match self {
            Ty::U8 | Ty::I8 => 8,
            Ty::U16 | Ty::I16 => 16,
        }
    }
    fn signed(self) -> bool {
        matches!(self, Ty::I8 | Ty::I16)
    }
    fn wide(self) -> bool {
        self.bits() == 16
    }
    fn min(self) -> i64 {
        if self.signed() {
            -(1i64 << (self.bits() - 1))
        } else {
            0
        }
    }
    fn max(self) -> i64 {
        if self.signed() {
            (1i64 << (self.bits() - 1)) - 1
        } else {
            (1i64 << self.bits()) - 1
        }
    }
}

/// The two types a program mixes: a narrow one, and the wide one it widens to
/// without an `as`.
///
/// The language's only quiet conversions between integers are `u8` -> `u16` and
/// `i8` -> `i16` — lossless, and within one signedness. `u8` -> `i16` is a type
/// error even though every `u8` fits an `i16`, and so is every narrowing. So a
/// program that mixes widths mixes exactly one such pair, and every other
/// conversion in it is written out.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
struct Pair {
    narrow: Ty,
    wide: Ty,
}

const PAIRS: [Pair; 2] = [
    Pair {
        narrow: Ty::U8,
        wide: Ty::U16,
    },
    Pair {
        narrow: Ty::I8,
        wide: Ty::I16,
    },
];

impl Pair {
    /// The two types, so a generator can pick one.
    fn both(self) -> [Ty; 2] {
        [self.narrow, self.wide]
    }
    fn pick(self, rng: &mut Rng) -> Ty {
        self.both()[rng.below(2) as usize]
    }
}

/// Wrap a value into `ty`, exactly as the language does: "all arithmetic
/// operators wrap on overflow", and a narrowing cast keeps the low bits.
fn narrow(v: i64, ty: Ty) -> i64 {
    let bits = ty.bits();
    let w = v & ((1i64 << bits) - 1);
    if ty.signed() && w > ty.max() {
        w - (1i64 << bits)
    } else {
        w
    }
}

/// The bit pattern that lands in memory, which is what the emulator reports.
fn raw(v: i64, ty: Ty) -> u32 {
    (v & ((1i64 << ty.bits()) - 1)) as u32
}

