// Generation
// ---------------------------------------------------------------------------

struct Gen<'a> {
    rng: &'a mut Rng,
    /// The widths this program mixes, and the type its aggregates take.
    pair: Pair,
    base: Ty,
    /// The type of each variable the scope being generated can name, indexed as
    /// `E::Var`. An expression at type `T` may name only the ones whose type is
    /// exactly `T`: the operands of an operator have to agree, and the language
    /// widens at boundaries rather than inside expressions.
    var_types: Vec<Ty>,
    /// Loop ids currently in scope, innermost last.
    scope: Vec<usize>,
    /// Start value of each `while` counter, by id.
    counters: Vec<u32>,
    loops: usize,
    /// Variables `E::Var` may index in the scope being generated.
    vars: usize,
    /// Which of them an assignment may target. A parameter is immutable —
    /// "only `let` locals and `static` globals can be assigned" — so inside a
    /// function this is the locals alone.
    assignable: std::ops::Range<usize>,
    /// The signature of each function generated so far.
    sigs: Vec<Sig>,
    /// Functions this scope may call. Restricted to higher-numbered ones inside
    /// a function body, so the call graph is acyclic and the only recursion is
    /// the explicit `SelfCall`.
    callable: std::ops::Range<usize>,
    /// May a self-call be generated here? False in a base case, and false once
    /// one has been placed — one self-call per function keeps the recursion
    /// linear rather than exponential in the depth budget.
    self_call: bool,
    /// The partner a mutual call may name here, on the same one-per-function
    /// terms as `self_call`. `None` outside the pair, in a base case, and once
    /// the call has been placed.
    mutual_call: Option<usize>,
    /// `for`/`while` are generated in `main` only; a loop inside a function
    /// would need its counter re-initialised per invocation, which is a
    /// separate question from the call machinery this reaches.
    allow_loops: bool,
    /// The array and the struct are `main`'s locals, so only `main`'s scope can
    /// name them. False inside a generated function, and false in a program
    /// that declares neither.
    allow_aggregates: bool,
    /// How many same-signature functions the table holds, or 0 when this
    /// program has no table. They are the highest-numbered functions, so the
    /// candidates are `funcs.len() - vtable ..`.
    vtable: usize,
    /// May an indirect call be generated here? `main` only, for the same
    /// reason as the aggregates: `DEV` is program state, and letting a callee
    /// read it would make a call something other than a function of its
    /// arguments. Also false while generating the candidates themselves, which
    /// keeps them out of their own dispatch and the call graph acyclic.
    allow_indirect: bool,
    /// The function that takes a slice parameter, when the program has one.
    /// Always `f0`, and unreachable from any function body, so a call site that
    /// names it is in `main` and has a slice to pass.
    slice_taker: Option<usize>,
    /// The function that takes a struct parameter, chosen the same way and for
    /// the same reasons as [`Gen::slice_taker`].
    struct_taker: Option<usize>,
    /// The function that takes an enum parameter, chosen like the other two.
    enum_taker: Option<usize>,
    /// The function that takes a `str` parameter, chosen like the others.
    str_taker: Option<usize>,
    /// May the string's length be named here?
    allow_str: bool,
    /// The length of `main`'s string, for a constant index that has to land
    /// inside it — a literal may be shorter than [`ALEN`]. Zero when there is
    /// no string.
    str_len: usize,
    /// May the enum's tag be named here? True in `main` when the program
    /// declares one, and inside the function that takes it.
    allow_enum: bool,
    /// May `s.f{i}` be generated here? True in `main` when the program has
    /// aggregates, and inside the struct-taking function, where the same node
    /// renders against its parameter instead. Separate from `allow_aggregates`
    /// because `arr` and `TBL` are *not* in scope inside a function and a
    /// field now is.
    allow_fields: bool,
    /// May a slice expression be generated here? True in `main` when the
    /// program declares slices, and inside `f0` when it takes one — the same
    /// restriction as the other aggregates, for the same reason.
    allow_slices: bool,
    /// The pointer `main` declares: its type, and which of `main`'s variables
    /// it may name. Empty in a program without one, and inside every function
    /// — `p` is `main`'s local, and nothing else can spell it.
    ///
    /// Every target has the pointer's own type, so a store through it is never
    /// a widening: `&T` names a `T`, and the two ways of writing that storage
    /// have to agree byte for byte.
    ptr_targets: Vec<PtrTarget>,
    ptr_ty: Ty,
    /// Whether `pk` exists, and which of `main`'s variables can take its
    /// result. Those are the ones at the aggregate type: `pk` returns a field,
    /// so anything else would put a widening in the way of the answer.
    poke_targets: Vec<usize>,
    /// May a `PokePtr` be generated here, and which of `main`'s variables it
    /// may write through the pointer. `main` only, like the aggregates.
    allow_pass_ptr: bool,
    bp_targets: Vec<usize>,
    /// May `**pp` be read or written here — the pointer-to-pointer. `main` only.
    allow_pp: bool,
    /// How many `sl{i}` are in scope: `SLICES` in `main`, and 0 inside a
    /// function, where the only slice is the parameter. What separates the two
    /// is that a statement can *move* a named slice, and `sp` is not one.
    main_slices: usize,
    /// The function being generated, for a self-call's signature. Unused in
    /// `main`, which has no self-call.
    current_fn: usize,
    /// The vtable candidates' shared `(parameter, return)` types, or `None`
    /// when this program has no table. They must agree to sit in one array.
    cand_sig: Option<(Ty, Ty)>,
    /// Bytes still available in the compiler's fixed argument-staging pool.
    /// A call whose whole argument list fits stages there; one that does not
    /// moves each argument to the software stack as it is evaluated, holding
    /// only its widest argument in the pool. So a nesting level costs one
    /// argument, not the list — which is what this charges. The budget cannot
    /// be exact (the pool has consumers a program's source does not reveal),
    /// so a seed that overruns anyway is skipped and counted.
    pool_left: u8,
}

/// The compiler's argument-staging pool, in bytes (`TempAllocator::ARG_SIZE`).
const ARG_POOL_BYTES: u8 = 11;

impl Gen<'_> {
    fn lit(&mut self, ty: Ty) -> i64 {
        // `-128` as a literal would be unary minus applied to an out-of-range
        // `128`; the value is still reachable by arithmetic.
        let lo = if ty.signed() { ty.min() + 1 } else { ty.min() };
        lo + self.rng.below((ty.max() - lo + 1) as u64) as i64
    }

    /// Whether an expression at `ty` has anything of that type to name.
    ///
    /// A run of pure literals carries no program type — the language types it
    /// from the literals' own range — so an expression at a type with no
    /// variable and no aggregate to anchor it has to be a *bare* literal,
    /// which does adopt the type its context expects. Anything compound would
    /// be typed by its own literals and the oracle would evaluate it at the
    /// wrong width.
    fn anchorable(&self, ty: Ty) -> bool {
        (!self.ptr_targets.is_empty() && self.ptr_ty == ty)
            || self.var_types.contains(&ty)
            || (self.allow_aggregates && self.base == ty)
            || (self.allow_slices && self.base == ty)
    }
}

/// `anchored` means the result must mention a variable. A run of pure literals
/// carries no program type: the language types it from the literals' own range,
/// so `0 >= (3 << 7)` is a `u8` comparison even inside an `i8` program, and the
/// shift wraps at eight bits rather than the program's width. Giving every
/// operator at least one anchored operand — the left one, plus a cast's operand
/// — keeps every subexpression at the program's type, which is the type the
/// oracle evaluates at. A bare literal beside an anchored sibling is fine: it
/// adopts the sibling's type.
fn gen_expr(g: &mut Gen, ty: Ty, depth: u32, anchored: bool) -> E {
    // Nothing of this type is in scope, so only a bare literal is safe: it
    // adopts the type its context expects, where a compound run of literals
    // would be typed by its own range instead.
    if !g.anchorable(ty) {
        return E::Lit(g.lit(ty));
    }
    if depth == 0 || g.rng.below(100) < 30 {
        // An element or a field is storage of the program's type, so it anchors
        // an expression exactly as a variable does.
        if g.allow_aggregates && g.base == ty && g.rng.below(100) < 35 {
            return match g.rng.below(5) {
                0 => E::Elem(gen_index(g)),
                1 => E::Konst(gen_index(g)),
                2 => E::Field(g.rng.below(SFIELDS as u64) as usize),
                3 => E::AField(gen_afield_index(g)),
                // A scalar of the struct nested inside the struct — the
                // two-level `s.n.g{j}` chain.
                _ => E::NestedField(g.rng.below(NESTED as u64) as usize),
            };
        }
        // Inside the struct-taking function the array and the table are out of
        // scope but a field is not: it reads through the parameter.
        if g.allow_fields && !g.allow_aggregates && g.base == ty && g.rng.below(100) < 35 {
            // Including its *array* field, indexed through the by-reference
            // parameter — `xp.a[i]`, which the compiler refused until the
            // element address became a run-time computation — and the scalar of
            // the struct nested inside it, `xp.n.g{j}`, a two-level offset
            // through the pointer where `main`'s `s.n.g{j}` is a two-level
            // offset from a label.
            return match g.rng.below(4) {
                0 => E::AField(gen_afield_index(g)),
                1 => E::NestedField(g.rng.below(NESTED as u64) as usize),
                _ => E::Field(g.rng.below(SFIELDS as u64) as usize),
            };
        }
        // A read through the pointer. Storage of its own type, so it anchors
        // an expression exactly as a variable does — and unlike a variable,
        // *which* storage is not known until the last `Repoint` has run.
        if !g.ptr_targets.is_empty() && g.ptr_ty == ty && g.rng.below(100) < 18 {
            // The pointer-to-pointer reaches the same value by a double
            // dereference — a different lowering the compiler was fixed for once.
            return if g.allow_pp && g.rng.below(100) < 40 {
                E::PtrPtrLoad
            } else {
                E::PtrLoad
            };
        }
        // The tag is a small number cast to the expression's type, so unlike a
        // field it fits any type and is not tied to the aggregate one.
        if g.allow_enum && g.rng.below(100) < 12 {
            return E::EnumVal;
        }
        // A `match` that extracts the payload — the tagged-union half the tag
        // read cannot reach. `main` only (it spells `e`), and `allow_loops` is
        // the `main`-only signal.
        if g.allow_enum && g.allow_loops && g.rng.below(100) < 10 {
            return E::EnumMatch;
        }
        // A string's `.len` is deliberately *not* generated freely. Reading it
        // stages the pointer through the four-byte high pool, so two of them
        // inside a multiply or a 16-bit operator exhaust it: at 12% of
        // expressions, 790 of 6000 seeds stopped compiling. The one folded into
        // the struct-taker's return is what tests the staging, and one per call
        // is enough for that.
        // A slice element and a slice length are both storage of the program's
        // type once cast, so either anchors an expression as a variable does.
        if g.allow_slices && g.rng.below(100) < 20 {
            // Inside a function the only slice is `sp`, which every slice
            // expression there names; rendering keys off the scope.
            let i = g.rng.below(g.main_slices.max(1) as u64) as usize;
            // `.len` is a `u16` the source casts to the context type, so it
            // fits any of them; an element is storage at the aggregate type.
            if g.rng.below(100) < 30 {
                return E::SliceLen(i);
            }
            if g.base == ty {
                return E::SliceElem(i, gen_slice_index(g));
            }
        }
        // Only variables of exactly this type: an operator's operands have to
        // agree, and this expression may end up under one.
        let named: Vec<usize> = (0..g.vars).filter(|i| g.var_types[*i] == ty).collect();
        let choices = if g.scope.is_empty() || named.is_empty() {
            2
        } else {
            3
        };
        let pick = if anchored && !named.is_empty() {
            1 + g.rng.below(choices - 1)
        } else if named.is_empty() {
            // No variable of this type, but an aggregate anchored us here, so
            // a literal or a loop variable is still safe beside one.
            if g.scope.is_empty() {
                0
            } else {
                g.rng.below(2) * 2
            }
        } else {
            g.rng.below(choices)
        };
        return match pick {
            0 => E::Lit(g.lit(ty)),
            1 => E::Var(named[g.rng.below(named.len() as u64) as usize]),
            _ => {
                let k = g.rng.below(g.scope.len() as u64) as usize;
                E::Loop(g.scope[k])
            }
        };
    }

    // A call. Its type comes from the callee's signature, so it anchors an
    // expression the way a variable does, and putting one under an operator is
    // what forces the other operand to be spilled across the JSR.
    // A call's type is its callee's return type, so it can only stand where
    // that is what is wanted. Its *argument* is a boundary, and may widen.
    if g.self_call && g.sigs[g.current_fn].ret == ty && g.rng.below(100) < 25 {
        g.self_call = false;
        let at = g.sigs[g.current_fn].params[0];
        return E::SelfCall(Box::new(gen_arg(g, at, depth - 1)));
    }
    if let Some(partner) = g.mutual_call
        && g.sigs[partner].ret == ty
        && g.rng.below(100) < 25
    {
        g.mutual_call = None;
        let at = g.sigs[partner].params[0];
        return E::MutualCall(partner, Box::new(gen_arg(g, at, depth - 1)));
    }
    // An indirect call. Same cost to the staging pool as a direct one-argument
    // call — the argument is evaluated into the pool before being copied to
    // the fixed indirect block — so it is budgeted the same way.
    if g.allow_indirect && g.vtable > 0 && g.cand_sig.is_some_and(|(_, r)| r == ty) {
        let (param_ty, _) = g.cand_sig.expect("checked just above");
        let cost = if param_ty.wide() { 2 } else { 1 };
        if g.rng.below(100) < 16 && cost <= g.pool_left {
            let saved = g.pool_left;
            g.pool_left -= cost;
            let arg = Box::new(gen_arg(g, param_ty, depth - 1));
            g.pool_left = saved;
            return if g.rng.below(2) == 0 {
                E::DevCall(arg)
            } else {
                let sel = if g.rng.below(2) == 0 {
                    Sel::Lit(g.rng.below(g.vtable as u64) as usize)
                } else {
                    Sel::Wrapped(g.rng.below(VARS as u64) as usize)
                };
                E::Dispatch { sel, arg }
            };
        }
    }

    if !g.callable.is_empty() && g.rng.below(100) < 14 {
        let id =
            g.callable.start + g.rng.below((g.callable.end - g.callable.start) as u64) as usize;
        let sig = g.sigs[id].clone();
        if sig.ret != ty {
            return gen_expr(g, ty, 0, anchored);
        }
        let takes_slice = g.slice_taker == Some(id);
        let takes_struct = g.struct_taker == Some(id);
        let takes_enum = g.enum_taker == Some(id);
        let takes_str = g.str_taker == Some(id);
        let widest = sig.params.iter().any(|t| t.wide());
        // The wide parameters are charged *together*, not by the widest of
        // them. That distinction did not exist while a callee could carry at
        // most one aggregate; `f0` can now carry four — a four-byte descriptor
        // and three two-byte addresses — and they are staged side by side, so
        // the level holds their sum. Charging the maximum instead put 7 of 120
        // seeds over the pool, which the budget's own guard caught.
        let aggregate_cost: u8 = u8::from(takes_slice) * 4
            + u8::from(takes_struct) * 2
            + u8::from(takes_enum) * 2
            + u8::from(takes_str) * 2;
        let cost = if aggregate_cost > 0 {
            aggregate_cost
        } else if widest {
            2
        } else {
            1
        };
        if cost <= g.pool_left {
            let saved = g.pool_left;
            g.pool_left -= cost;
            let args = sig
                .params
                .iter()
                .map(|pt| gen_arg(g, *pt, depth - 1))
                .collect();
            g.pool_left = saved;
            let budget = sig
                .recursive
                .then(|| g.rng.below(RECURSION_BUDGET as u64 + 1) as u32);
            let slice_arg = (takes_slice && g.main_slices > 0)
                .then(|| g.rng.below(g.main_slices as u64) as usize);
            return E::Call {
                id,
                budget,
                args,
                slice_arg,
                struct_arg: takes_struct,
                enum_arg: takes_enum,
                str_arg: takes_str,
            };
        }
    }

    if g.rng.below(100) < 12 {
        let mut to = TYPES[g.rng.below(TYPES.len() as u64) as usize];
        if to == ty {
            to = TYPES[(TYPES.iter().position(|t| *t == ty).unwrap() + 1) % TYPES.len()];
        }
        return E::Cast(to, Box::new(gen_expr(g, ty, depth - 1, true)));
    }

    let op = OPS[g.rng.below(OPS.len() as u64) as usize];
    let lhs = gen_expr(g, ty, depth - 1, true);
    let rhs = match op {
        // A divisor is an ordinary expression now that a zero one has an
        // answer. It is *anchored*, which keeps it from being a constant: a
        // divisor the compiler can see is zero is a compile error, and the
        // sentinel is for the divisor that is only zero sometimes.
        //
        // Anchoring is not airtight: where the divisor's type has no run-time
        // value in scope — an `i8` inside a function whose only scalars are
        // `u8` and `i16` — it degrades to literals, and `(-19) / 27` folds to
        // a constant zero the compiler rejects. So a divisor that folds to
        // zero is forced odd, hence non-zero; a run-time divisor (and its
        // sentinel coverage) is left untouched.
        Op::Div | Op::Rem => {
            let d = gen_expr(g, ty, depth - 1, true);
            if const_fold(&d, ty) == Some(0) {
                E::Bin(Box::new(d), Op::Or, Box::new(E::Lit(1)))
            } else {
                d
            }
        }
        Op::Shl | Op::Shr => E::Lit(g.rng.below(ty.bits() as u64) as i64),
        _ => gen_expr(g, ty, depth - 1, false),
    };
    E::Bin(Box::new(lhs), op, Box::new(rhs))
}

/// An expression at a *boundary*, where the language widens without an `as`:
/// a binding, an assignment, an argument, or a `return`.
///
/// Where the destination is the wide half of the pair, the expression is
/// sometimes generated at the narrow half instead and left to widen. What that
/// tests is the order of the two: the arithmetic happens at the narrow type and
/// the result is extended afterwards, so a sum that overflows a byte stays
/// overflowed. Getting it the other way round is fuzz bug 1 wearing a
/// different hat.
fn gen_arg(g: &mut Gen, want: Ty, depth: u32) -> E {
    let at = if want == g.pair.wide && g.rng.below(100) < 35 {
        g.pair.narrow
    } else {
        want
    };
    E::At(at, Box::new(gen_expr(g, at, depth, false)))
}

/// An index that is in range whatever the program computes.
fn gen_index(g: &mut Gen) -> Ix {
    let choices = if g.scope.is_empty() { 2 } else { 3 };
    match g.rng.below(choices) {
        0 => Ix::Lit(g.rng.below(ALEN as u64) as usize),
        1 => Ix::Wrapped(g.rng.below(VARS as u64) as usize),
        _ => {
            let k = g.rng.below(g.scope.len() as u64) as usize;
            Ix::Loop(g.scope[k])
        }
    }
}

/// An index into the struct's array field, which is [`AFLEN`] long rather than
/// [`ALEN`].
///
/// No loop variable: a `for` bound may be as large as `ALEN`, which is past the
/// end of this one, and an out-of-range write would be the generator's fault
/// rather than the compiler's.
fn gen_afield_index(g: &mut Gen) -> Ix {
    if g.rng.below(2) == 0 {
        // Never zero: a zero index adds nothing, so an index that is scaled by
        // the wrong width — or not scaled at all — reads the right byte anyway.
        // Index zero is still reached, by the wrapped form below landing on it.
        Ix::Lit(1 + g.rng.below(AFLEN as u64 - 1) as usize)
    } else {
        // The *enclosing* scope's variables, not `main`'s: inside the
        // struct-taking function there may be fewer, and they are named
        // differently.
        Ix::Wrapped(g.rng.below(g.vars as u64) as usize)
    }
}

/// An index into `main`'s string, in range whatever the program computes.
///
/// The literal form is bounded by the string's own length, which may be
/// shorter than [`ALEN`] — `"a"` has one byte — so it cannot reuse
/// [`gen_index`]. The wrapped form reduces modulo `t.len` at run time, like a
/// slice index, so it needs no compile-time length. No loop variable: a `for`
/// bound may reach [`ALEN`], past the end of a short string, and an
/// out-of-range read would be the generator's fault rather than the compiler's.
fn gen_str_index(g: &mut Gen) -> Ix {
    if g.rng.below(2) == 0 {
        Ix::Lit(g.rng.below(g.str_len.max(1) as u64) as usize)
    } else {
        Ix::Wrapped(g.rng.below(g.vars as u64) as usize)
    }
}

/// An index into a slice, which is in range whatever the slice currently
/// views.
///
/// Only the two forms whose range does not depend on the descriptor: a literal
/// `0`, and a variable reduced modulo the *run-time* length. A loop variable is
/// deliberately absent — its bound is fixed when the loop is generated, while a
/// `Reslice` can shorten the slice underneath it, and an out-of-range read
/// would be the generator's fault rather than the compiler's.
fn gen_slice_index(g: &mut Gen) -> Ix {
    if g.rng.below(2) == 0 {
        Ix::Lit(0)
    } else {
        // The *enclosing* scope's variables, not `main`'s: this is the one
        // index form generated inside a function, where there may be fewer.
        Ix::Wrapped(g.rng.below(g.vars as u64) as usize)
    }
}

/// A non-empty sub-range of `TBL`, as `(start, len)`.
fn gen_range(g: &mut Gen) -> (usize, usize) {
    let start = g.rng.below(ALEN as u64) as usize;
    let len = 1 + g.rng.below((ALEN - start) as u64) as usize;
    (start, len)
}

/// Where an assignment stores. Restricted to the locals a function may write:
/// a parameter is immutable, and the aggregates belong to `main`.
/// A place to store into, with the type it holds — which is what decides
/// whether the value assigned to it may widen.
fn gen_place(g: &mut Gen) -> (Place, Ty) {
    if g.allow_aggregates && g.rng.below(100) < 40 {
        let p = match g.rng.below(3) {
            0 => Place::Elem(gen_index(g)),
            1 => Place::Field(g.rng.below(SFIELDS as u64) as usize),
            _ => Place::AField(gen_afield_index(g)),
        };
        return (p, g.base);
    }
    let span = g.assignable.end - g.assignable.start;
    let i = g.assignable.start + g.rng.below(span as u64) as usize;
    (Place::Var(i), g.var_types[i])
}

fn gen_bool(g: &mut Gen, depth: u32) -> B {
    if depth > 0 && g.rng.below(100) < 45 {
        return match g.rng.below(3) {
            0 => B::And(
                Box::new(gen_bool(g, depth - 1)),
                Box::new(gen_bool(g, depth - 1)),
            ),
            1 => B::Or(
                Box::new(gen_bool(g, depth - 1)),
                Box::new(gen_bool(g, depth - 1)),
            ),
            _ => B::Not(Box::new(gen_bool(g, depth - 1))),
        };
    }
    // One type for both sides. Preferring one that is anchorable keeps the
    // comparison from collapsing to two bare literals, which the language
    // types from their own range rather than from the program around them.
    let mut ty = g.pair.pick(g.rng);
    if !g.anchorable(ty) {
        ty = if ty == g.pair.narrow {
            g.pair.wide
        } else {
            g.pair.narrow
        };
    }
    let l = gen_expr(g, ty, 2, true);
    let cmp = CMPS[g.rng.below(CMPS.len() as u64) as usize];
    let r = gen_expr(g, ty, 2, false);
    B::Rel(ty, Box::new(l), cmp, Box::new(r))
}

fn gen_block(g: &mut Gen, depth: u32) -> Vec<S> {
    let n = 1 + g.rng.below(if depth == 0 { 2 } else { 3 }) as usize;
    (0..n).flat_map(|_| gen_stmt_seq(g, depth)).collect()
}

/// One statement, plus — after a store through the pointer — a read of a
/// variable that store may have landed in.
///
/// The read comes *immediately* after because that is where the alias has to
/// hold: a value written under one name must be visible under the other at the
/// very next statement, with whatever the compiler believes about its
/// registers in between. Left to chance, whether any read follows a pointer
/// store at all is a coin toss.
///
/// It is not a complete guard on the invalidation that makes it true —
/// dropping `invalidate_registers` after an indirect store still survives 120
/// seeds and fails 1 of 2000, because the register cache rarely spans the
/// store even when nothing tells it not to. That thinness is recorded rather
/// than papered over.
///
/// The read is a plain copy between two variables of the pointer's own type,
/// so there is no widening in it and nothing to compute: what it tests is
/// where the value comes from.
fn gen_stmt_seq(g: &mut Gen, depth: u32) -> Vec<S> {
    let s = gen_stmt(g, depth);
    if matches!(s, S::PtrStore(..) | S::PtrPtrStore(..)) && !g.ptr_targets.is_empty() {
        // Read one alias candidate straight back, under its own name, right
        // after the store: a value written through `*p` has to be visible
        // through the storage it aliases, and a compiler keeping that storage
        // in a register across the store would answer with the stale one. The
        // candidate may be a variable, a field, or an element, so the read is
        // its direct access — the destination is any assignable variable of
        // the pointer's (pointee's) type.
        let k = g.rng.below(g.ptr_targets.len() as u64) as usize;
        let src = g.ptr_targets[k].read();
        if let Some(dst) = (g.assignable.clone()).find(|i| g.var_types[*i] == g.ptr_ty) {
            return vec![s, S::Assign(Place::Var(dst), g.ptr_ty, src)];
        }
    }
    vec![s]
}

fn gen_stmt(g: &mut Gen, depth: u32) -> S {
    // Rebinding the installed driver. Rare, and before the type check below,
    // because it is the one statement that carries no expression.
    if g.allow_indirect && g.vtable > 1 && g.rng.below(100) < 8 {
        let k = g.rng.below(g.vtable as u64) as usize;
        return S::Install(g.sigs.len() - g.vtable + k);
    }
    // Moving a descriptor, the same way and for the same reason: neither
    // statement carries an expression, and both change what a later read
    // reaches without any arithmetic being involved.
    if g.main_slices > 0 && g.rng.below(100) < 12 {
        let i = g.rng.below(g.main_slices as u64) as usize;
        return match g.rng.below(3) {
            0 => S::CopySlice(i, (i + 1) % g.main_slices),
            1 => {
                let (start, len) = gen_range(g);
                S::Reslice(i, start, len)
            }
            _ => S::SliceFromCall(i, g.rng.below(2) as usize),
        };
    }
    // The two pointer statements: a store through the alias, and a move of
    // the alias itself. Both before the type check below, like the other
    // statements that carry no place of their own.
    if !g.ptr_targets.is_empty() && g.rng.below(100) < 12 {
        if g.rng.below(3) == 0 {
            let k = g.rng.below(g.ptr_targets.len() as u64) as usize;
            return S::Repoint(g.ptr_targets[k].clone());
        }
        let ty = g.ptr_ty;
        return if g.allow_pp && g.rng.below(100) < 40 {
            S::PtrPtrStore(ty, gen_expr(g, ty, 2, false))
        } else {
            S::PtrStore(ty, gen_expr(g, ty, 2, false))
        };
    }
    // One of `main`'s variables written through a `&T` parameter, its new
    // value read back. `main` only, and its own statement: the pointer is
    // staged as a two-byte argument, and the alias is what makes the callee's
    // write visible in `main`.
    if g.allow_pass_ptr && !g.bp_targets.is_empty() && g.rng.below(100) < 10 {
        let t = g.bp_targets[g.rng.below(g.bp_targets.len() as u64) as usize];
        let d = g.bp_targets[g.rng.below(g.bp_targets.len() as u64) as usize];
        return S::PokePtr(t, d, gen_expr(g, g.base, 2, false));
    }
    // A field written through a `&S` inside a call, and another read back.
    if !g.poke_targets.is_empty() && g.rng.below(100) < 10 {
        let k = g.rng.below(g.poke_targets.len() as u64) as usize;
        let dst = g.poke_targets[k];
        let ty = g.base;
        return S::PokeStruct(dst, gen_expr(g, ty, 2, false));
    }
    // The whole struct replaced by one that arrives from a call. Beside the
    // slice moves above and for the same reason: the statement carries no
    // expression, and what it changes is what a later read reaches.
    if g.allow_aggregates && g.rng.below(100) < 8 {
        return S::StructFromCall(g.rng.below(2) as usize);
    }
    // A byte run copied out of the `const` table. Needs the aggregates to
    // exist, and a `u8` element: `memcpy` takes `&u8`, so an `i8` array would
    // need its address converted, and a byte count is an element count only at
    // a one-byte width.
    if g.allow_aggregates && g.base == Ty::U8 && g.rng.below(100) < 10 {
        let len = 1 + g.rng.below(ALEN as u64) as usize;
        let dst = g.rng.below((ALEN - len + 1) as u64) as usize;
        let src = g.rng.below((ALEN - len + 1) as u64) as usize;
        return S::CopyRange { dst, src, len };
    }
    // A byte of the string read straight into a variable, on its own line
    // rather than folded into an expression. Reading it stages the pointer
    // through the four-byte high pool, and an arithmetic operand beside it —
    // a multiply, another string read — exhausts the pool, which is why `.len`
    // is not generated freely either. On its own statement, in `main`, the
    // pool has nothing else in it, so both the constant-offset lowering (the
    // offset folds into the pointer) and the runtime one (a `% t.len` index)
    // stage cleanly.
    if g.allow_str && g.allow_loops && !g.assignable.is_empty() && g.rng.below(100) < 14 {
        let k = g.assignable.start + g.rng.below(g.assignable.len() as u64) as usize;
        let ty = g.var_types[k];
        return S::Assign(Place::Var(k), ty, E::StrIndex(gen_str_index(g)));
    }
    let pick = g.rng.below(100);
    if depth == 0 || pick < 50 || (!g.allow_loops && pick >= 72) {
        let (place, want) = gen_place(g);
        // The target supplies the type, and is a boundary: a narrow value
        // stored into a wide slot widens with no syntax to mark it.
        return S::Assign(place, want, gen_arg(g, want, 3));
    }
    match pick {
        50..=71 => {
            let cond = gen_bool(g, 2);
            let then = gen_block(g, depth - 1);
            let otherwise = if g.rng.below(2) == 0 {
                Some(gen_block(g, depth - 1))
            } else {
                None
            };
            S::If(cond, then, otherwise)
        }
        72..=87 => {
            let id = g.loops;
            g.loops += 1;
            // Capped at the array length so a loop variable is always a valid
            // index (see `Ix::Loop`).
            let count = 1 + g.rng.below(ALEN as u64) as u32;
            g.scope.push(id);
            let body = gen_block(g, depth - 1);
            g.scope.pop();
            S::For(id, count, body)
        }
        _ => {
            let id = g.counters.len();
            let start = 1 + g.rng.below(4) as u32;
            g.counters.push(start);
            let body = gen_block(g, depth - 1);
            S::While(id, body)
        }
    }
}

/// A `match` on an integer, in `main`: either a few distinct literal arms or one
/// range arm, always disjoint, plus a wildcard. Patterns are non-negative and
/// within the base type; a 16-bit base allows a bound past 255, so the range
/// compare has to look past the low byte to route correctly.
fn gen_int_match(g: &mut Gen, depth: u32) -> S {
    let base = g.base;
    let scrut = gen_expr(g, base, 2, false);
    let cap = (base.max() as u64).min(400);
    let mut arms: Vec<(MatchPat, Vec<S>)> = Vec::new();
    if g.rng.below(100) < 55 {
        let n = 1 + g.rng.below(3) as usize;
        let mut used: Vec<i64> = Vec::new();
        for _ in 0..n {
            let v = g.rng.below(cap + 1) as i64;
            if !used.contains(&v) {
                used.push(v);
                let body = gen_block(g, depth - 1);
                arms.push((MatchPat::Lit(v), body));
            }
        }
    } else {
        let a = g.rng.below(cap + 1) as i64;
        let b = g.rng.below(cap + 1) as i64;
        let (lo, hi) = if a <= b { (a, b) } else { (b, a) };
        // An exclusive `lo..hi` is empty when `lo == hi`; make that one inclusive.
        let inclusive = lo == hi || g.rng.below(2) == 0;
        let body = gen_block(g, depth - 1);
        arms.push((MatchPat::Range(lo, hi, inclusive), body));
    }
    let default = gen_block(g, depth - 1);
    S::IntMatch {
        scrut,
        arms,
        default,
    }
}

#[derive(Clone)]
struct Prog {
    /// The pair of widths this program mixes.
    pair: Pair,
    /// The type of the aggregates: the array, the struct's fields, the `const`
    /// table and the slices over it. One type for all of them, so an element
    /// read anchors an expression at exactly that type and mixing stays a
    /// question about variables and signatures.
    base: Ty,
    /// The type of each of `main`'s variables.
    var_types: [Ty; VARS],
    init: [i64; VARS],
    counters: Vec<u32>,
    stmts: Vec<S>,
    loops: usize,
    funcs: Vec<Func>,
    /// Whether this program declares the array and the struct. Not every
    /// program does, so the scalar shapes keep being generated too.
    aggregates: bool,
    arr_init: [i64; ALEN],
    field_init: [i64; SFIELDS],
    /// The struct's array field, initialised with the struct and written by
    /// `Place::AField`.
    afield_init: [i64; AFLEN],
    /// The nested struct's scalar fields, initialised with the struct. Never
    /// written — the nested field is read-only — so it changes only when the
    /// whole struct is replaced by a `mks` call.
    nested_init: [i64; NESTED],
    /// Which variant `main`'s enum local holds, or `None` when the program
    /// declares no enum.
    enum_init: Option<usize>,
    /// The payload the constructed variant carries, at [`Self::enum_payload_ty`].
    /// Variants past the first hold one; variant 0 is unit and ignores this.
    enum_payload: i64,
    /// Whether the payload variants carry the pair's *wide* type rather than a
    /// `u8`. A two-byte payload is extracted into A:X and cast down, a different
    /// register convention from the one-byte case.
    enum_payload_wide: bool,
    /// Which of [`STRINGS`] `main` holds, or `None` when it holds none.
    str_init: Option<usize>,
    /// The `const` table's contents. Declared whenever `aggregates` is set, and
    /// never written, so it needs no cell in the state.
    konst: [i64; ALEN],
    /// How many of the highest-numbered functions sit in the function-pointer
    /// table, or 0 for a program without one.
    vtable: usize,
    /// The declared range of each slice over `TBL`, as `(start, len)`. Empty
    /// in a program without the table. These are the *initial* descriptors —
    /// `S::Reslice` and `S::CopySlice` move them, which is why the state
    /// carries its own copy.
    slices: Vec<(usize, usize)>,
    /// The two ranges `mk` chooses between. Present exactly when `slices` is
    /// non-empty; `mk` is what makes a slice arrive from a call.
    mk_ranges: Vec<(usize, usize)>,
    /// The two structs `mks` chooses between, as (scalar fields, array field).
    /// Present exactly when the program declares the struct.
    mks: Vec<([i64; SFIELDS], [i64; AFLEN], [i64; NESTED])>,
    /// The two fields `pk` writes and reads, or `None` in a program that has
    /// no `pk`. Fixed per program because they are part of the function.
    poke: Option<(usize, usize)>,
    /// Whether the program declares `bp`, the helper that writes one of
    /// `main`'s variables through a `&T` parameter.
    pass_ptr: bool,
    /// Whether `main` declares `pp: &&T = &p`, a pointer to the pointer.
    has_pp: bool,
    /// The pointer `main` declares, as (type, initial target). `None` in a
    /// program without one.
    ptr: Option<(Ty, PtrTarget)>,
    /// Which of them `main`'s struct is *bound* from, or `None` when it is
    /// declared from a literal.
    ///
    /// Binding and assignment are separate code — `let s: S = mks(0);` copies
    /// the returned bytes out in `generate_var_decl`, `s = mks(0);` does it
    /// again in `generate_assign` — so generating only one leaves the other's
    /// length free to be wrong. Truncating the binding copy to two bytes
    /// survives 120 seeds when only the assignment form is generated.
    struct_init_from_call: Option<usize>,
    /// The mutually recursive pair, low id first, or `None`. Both members carry
    /// a budget and call each other at `d - 1`, so the cycle terminates by the
    /// same construction a self-call does.
    mutual: Option<(usize, usize)>,
    /// The initial value of `main`'s mutable `static GSTATIC`, or `None` when
    /// the program declares none. Its type is `base`. Unlike the `const` table
    /// this lives in RAM (BSS): the reset handler writes the initial value, and
    /// `S::GStore` overwrites it, so the state carries its own copy.
    mut_static: Option<i64>,
}

impl Prog {
    /// The function id of table entry `k`.
    fn candidate(&self, k: usize) -> usize {
        self.funcs.len() - self.vtable + k
    }
    /// The declared type of a payload variant's field: the pair's wide type when
    /// the payload is two bytes, `u8` otherwise.
    fn enum_payload_ty(&self) -> Ty {
        if self.enum_payload_wide {
            self.pair.wide
        } else {
            Ty::U8
        }
    }
}

/// The largest recursion budget a call site may pass. Well under the depth the
/// software stack allows (the compiler warns around 85), so a generated program
/// tests the frame save/restore rather than the limit — and the call tree stays
/// linear, since a function holds at most one self-call.
const RECURSION_BUDGET: u32 = 5;

/// Build the functions first, back to front: `f0` may call `f1`, `f1` may call
/// `f2`, and none may call a lower-numbered one, so the call graph is acyclic
/// and the only cycle in the program is the explicit self-call.
fn gen_funcs(g: &mut Gen, count: usize, mutual: Option<(usize, usize)>) -> Vec<Func> {
    let mut funcs: Vec<Func> = Vec::new();
    // Indexed by function id, so a caller can look up a callee generated
    // earlier in this back-to-front walk.
    g.sigs = vec![
        Sig {
            params: Vec::new(),
            ret: g.base,
            recursive: false,
        };
        count
    ];
    // The pair's signatures have to be known before either body is generated:
    // the higher-numbered member is generated first and calls the lower one,
    // which the back-to-front walk has not reached yet. Both are shaped like
    // the self-recursive function — a budget and one value parameter — so the
    // mutual call has an argument to vary. They also share a type on both
    // sides, so either can pass its own result straight back to the other.
    if let Some((a, b)) = mutual {
        let mt = g.pair.pick(g.rng);
        for k in [a, b] {
            g.sigs[k] = Sig {
                params: vec![mt],
                ret: mt,
                recursive: true,
            };
        }
    }
    // The candidates share one signature or they cannot sit in one array.
    if let Some((pt, rt)) = g.cand_sig {
        for k in count - g.vtable..count {
            g.sigs[k] = Sig {
                params: vec![pt],
                ret: rt,
                recursive: false,
            };
        }
    }
    for i in (0..count).rev() {
        // The highest-numbered functions are the table's candidates. They must
        // share one signature to sit in the same array, so they take a single
        // parameter and do not recurse — a recursive one carries a depth
        // budget, which changes the type.
        let is_candidate = i >= count - g.vtable;
        // A member of the mutual pair, and if so, which function it calls back.
        let partner = mutual.and_then(|(a, b)| match i {
            _ if i == a => Some(b),
            _ if i == b => Some(a),
            _ => None,
        });
        // `f0` alone may take a slice — but not while it is half of the pair.
        // Its partner would have to pass one on every mutual call, and a pair
        // member has none: they are shaped alike so the cycle closes.
        let slice_param = i == 0 && !is_candidate && g.allow_slices && partner.is_none();
        // The struct rides on the same function and under the same three
        // conditions, for the same reasons: a vtable candidate is reached by an
        // indirect call, which stages at a fixed address and cannot carry an
        // aggregate; a pair member's partner would have to pass one on every
        // mutual edge. `allow_fields` is the struct's `allow_slices` — set
        // before the functions are generated, because this is where it is read.
        let struct_param = i == 0 && !is_candidate && g.allow_fields && partner.is_none();
        // Independent of the other two, so the three wide parameters appear in
        // every combination rather than always together.
        let enum_param = i == 0 && !is_candidate && g.allow_enum && partner.is_none();
        let str_param = i == 0 && !is_candidate && g.allow_str && partner.is_none();
        // At most two of the four, chosen at random among those eligible.
        //
        // All four is not a shape worth generating: a descriptor and three
        // addresses are ten of the argument pool's eleven bytes before a
        // single value parameter, so the call cannot be staged at all and the
        // seed is skipped. Two still reaches what matters — several wide
        // arguments staged side by side, where an offset that assumes one byte
        // each goes wrong — while leaving room for the scalars around them.
        let (slice_param, struct_param, enum_param, str_param) = {
            let mut wide = [slice_param, struct_param, enum_param, str_param];
            let mut taken = wide.iter().filter(|w| **w).count();
            while taken > 2 {
                let k = g.rng.below(wide.len() as u64) as usize;
                if wide[k] {
                    wide[k] = false;
                    taken -= 1;
                }
            }
            (wide[0], wide[1], wide[2], wide[3])
        };
        // Read once here: the signature below needs it, and so does the return
        // expression further down.
        let takes_struct = struct_param;
        let takes_enum = enum_param;
        let takes_str = str_param;
        // Otherwise the last function is the one allowed to recurse, and a
        // recursive one takes exactly one value parameter besides its budget,
        // so the self-call has one argument to vary. A pair member is recursive
        // through its partner instead — one cycle per function either way.
        let recursive = partner.is_some()
            || (!is_candidate && i + 1 == count - g.vtable && g.rng.below(2) == 0);
        // A pair member's and a candidate's signature were fixed above; any
        // other function picks its own parameter and return types from the
        // pair, which is where a mixed-width call site comes from.
        let sig = if partner.is_some() || is_candidate {
            g.sigs[i].clone()
        } else {
            // A self-recursive function takes exactly one value parameter
            // besides its budget: `SelfCall` passes one argument, so the
            // recursion has one thing to vary and the shape stays fixed.
            let n = if recursive {
                1
            } else {
                1 + g.rng.below(3) as usize
            };
            let s = Sig {
                params: (0..n).map(|_| g.pair.pick(g.rng)).collect(),
                // The struct-taking function returns the aggregate type, so a
                // field read is type-compatible with its return expression and
                // can be folded into it below. Both are halves of the pair, so
                // this is a legal pick and not a new type.
                ret: if takes_struct {
                    g.base
                } else {
                    g.pair.pick(g.rng)
                },
                recursive,
            };
            g.sigs[i] = s.clone();
            s
        };
        let params = sig.params.len();
        let local_types: Vec<Ty> = (0..g.rng.below(3)).map(|_| g.pair.pick(g.rng)).collect();
        let locals: Vec<i64> = local_types.iter().map(|t| g.lit(*t)).collect();
        let mut var_types = sig.params.clone();
        var_types.extend(local_types.iter().copied());

        let saved_vars = g.vars;
        let saved_assignable = g.assignable.clone();
        let saved_callable = g.callable.clone();
        let saved_loops = g.allow_loops;
        let saved_aggregates = g.allow_aggregates;
        let saved_slices = g.allow_slices;
        let saved_main_slices = g.main_slices;
        let saved_fields = g.allow_fields;
        let saved_enum = g.allow_enum;
        let saved_str = g.allow_str;
        g.allow_aggregates = false;
        // Inside the function the only slice in scope is its own parameter,
        // which every slice expression there names and no statement can move.
        g.allow_slices = slice_param;
        // A field, unlike the array and the table, *is* in scope inside the
        // function that takes the struct — reached through `xp` rather than
        // through `main`'s `s`, which is the renderer's business, not the
        // generator's.
        g.allow_fields = struct_param;
        g.allow_enum = enum_param;
        g.allow_str = str_param;
        g.main_slices = 0;
        let saved_var_types = std::mem::replace(&mut g.var_types, var_types.clone());
        let saved_current = g.current_fn;
        g.current_fn = i;
        g.vars = params + locals.len();
        g.assignable = params..params + locals.len();
        // The lower member of the pair may not call the higher one *except*
        // through its `MutualCall`, which decrements the budget. An ordinary
        // call passes a fresh literal one, so the cycle would reset its own
        // depth every second edge and never terminate. The two are adjacent by
        // construction, so skipping one id is enough to say that.
        g.callable = if partner == Some(i + 1) {
            i + 2..count
        } else {
            i + 1..count
        };
        g.allow_loops = false;

        // The base case first, with both kinds of recursive call unavailable:
        // recursing at `d == 0` would pass `d - 1` on a `u8` and wrap to 255.
        g.self_call = false;
        g.mutual_call = None;
        // The struct-taker's base case is built strictly at its own type, not
        // through `gen_arg`: a boundary operand may be generated at the *narrow*
        // half and rendered without a cast, and pairing that with a field of
        // the wide half under one operator is a type error, not a widening.
        // One term per wide parameter, folded into the result so that passing
        // each can be told apart from staging it wrongly.
        //
        // *Every* one of them, not the first: a function may take two, and
        // reading only one leaves the other passed but unobserved — which is
        // exactly the hole that made the struct work catch nothing until the
        // read was forced. A field is pinned to the aggregate type, which is
        // why the return type is forced to it; the tag and the length are
        // casts and fit whatever type they land in.
        let observable_terms = |g: &mut Gen| -> Vec<E> {
            let mut ts = Vec::new();
            if takes_struct {
                // Either kind of field, because both have to *reach the
                // result*: a read left in a local the return never uses proves
                // nothing, and the array field's index arithmetic is the half
                // with no other way in.
                ts.push(if g.rng.below(2) == 0 {
                    E::AField(gen_afield_index(g))
                } else {
                    E::Field(g.rng.below(SFIELDS as u64) as usize)
                });
            }
            if takes_enum {
                ts.push(E::EnumVal);
            }
            if takes_str {
                ts.push(E::StrLen);
            }
            ts
        };
        let fold = |acc: E, ts: Vec<E>| -> E {
            ts.into_iter()
                .fold(acc, |a, t| E::Bin(Box::new(a), Op::Add, Box::new(t)))
        };
        let base = {
            let ts = observable_terms(g);
            if ts.is_empty() {
                gen_arg(g, sig.ret, 2)
            } else {
                fold(gen_expr(g, sig.ret, 2, false), ts)
            }
        };

        // Statements need somewhere to assign, and a parameter is not it, so a
        // function with no locals is a bare `return`.
        let n = if locals.is_empty() {
            0
        } else {
            g.rng.below(3) as usize
        };
        let body: Vec<S> = (0..n).map(|_| gen_stmt(g, 1)).collect();

        // Exactly one recursive call, in the returned expression, so it is
        // always reached when `d > 0` and the recursion is linear in the
        // budget. A pair member recurses through its partner; every other
        // recursive function calls itself.
        g.self_call = recursive && partner.is_none();
        g.mutual_call = partner;
        let ret = if recursive {
            // The recursive call returns this function's own type, so the
            // operator around it works at that type and no widening applies.
            let rt = sig.ret;
            let arg = gen_arg(g, sig.params[0], 2);
            let other = gen_expr(g, rt, 2, false);
            let call = match partner {
                Some(p) => E::MutualCall(p, Box::new(arg)),
                None => E::SelfCall(Box::new(arg)),
            };
            let op = OPS[g.rng.below(OPS.len() as u64) as usize];
            // Both operand orders: with the call on the right, the left operand
            // has to survive the JSR, which is the software-stack spill path.
            match op {
                Op::Div | Op::Rem | Op::Shl | Op::Shr => {
                    E::Bin(Box::new(call), Op::Add, Box::new(E::Lit(g.lit(rt))))
                }
                _ if g.rng.below(2) == 0 => E::Bin(Box::new(call), op, Box::new(other)),
                _ => E::Bin(Box::new(other), op, Box::new(call)),
            }
        } else if takes_struct || takes_enum || takes_str {
            // Passing the struct proves nothing unless its value reaches an
            // output cell, and generation alone does not get there: a field
            // read landed in a local the return never used, so staging the
            // argument wrongly changed no answer and the fuzzer stayed quiet
            // with the bug in place. So the struct-taker's result *is* a
            // function of a field. Both operands at its own type, for the
            // reason given at the base case above.
            fold(gen_expr(g, sig.ret, 3, false), observable_terms(g))
        } else {
            gen_arg(g, sig.ret, 3)
        };
        // A recursive struct-taker returns its base case at `d == 0`, which is
        // why that carries a field read too — otherwise a budget of zero hides
        // the argument entirely.
        let ret = if recursive {
            fold(ret, observable_terms(g))
        } else {
            ret
        };
        g.self_call = false;
        g.mutual_call = None;

        g.vars = saved_vars;
        g.assignable = saved_assignable;
        g.callable = saved_callable;
        g.allow_loops = saved_loops;
        g.allow_aggregates = saved_aggregates;
        g.allow_fields = saved_fields;
        g.allow_enum = saved_enum;
        g.allow_str = saved_str;
        g.allow_slices = saved_slices;
        g.main_slices = saved_main_slices;
        g.var_types = saved_var_types;
        g.current_fn = saved_current;

        funcs.push(Func {
            slice_param,
            struct_param,
            enum_param,
            str_param,
            partner,
            var_types,
            ret_ty: sig.ret,
            params,
            local_init: locals,
            recursive,
            body,
            ret,
            base,
        });
    }
    funcs.reverse();
    funcs
}

fn gen_program(seed: u64) -> Prog {
    let mut rng = Rng::new(seed);
    // One signedness family per program, so the pair it mixes is the pair the
    // language widens between. The aggregates take one of the two.
    let pair = PAIRS[rng.below(PAIRS.len() as u64) as usize];
    let base = pair.both()[rng.below(2) as usize];
    // `main`'s variables. Both halves of the pair always appear, so an
    // expression at either has something to name and a mixed-width assignment
    // is always available.
    let mut var_types = [pair.narrow; VARS];
    for (i, t) in var_types.iter_mut().enumerate() {
        *t = if i < 2 {
            pair.both()[i]
        } else {
            pair.both()[rng.below(2) as usize]
        };
    }
    let mut init = [0i64; VARS];
    let mut g = Gen {
        rng: &mut rng,
        pair,
        base,
        var_types: var_types.to_vec(),
        scope: Vec::new(),
        counters: Vec::new(),
        loops: 0,
        vars: VARS,
        assignable: 0..VARS,
        sigs: Vec::new(),
        callable: 0..0,
        self_call: false,
        mutual_call: None,
        allow_loops: true,
        allow_aggregates: false,
        ptr_targets: Vec::new(),
        ptr_ty: base,
        poke_targets: Vec::new(),
        allow_pass_ptr: false,
        bp_targets: Vec::new(),
        allow_pp: false,
        allow_fields: false,
        allow_enum: false,
        allow_str: false,
        str_len: 0,
        vtable: 0,
        allow_indirect: false,
        allow_slices: false,
        main_slices: 0,
        slice_taker: None,
        struct_taker: None,
        enum_taker: None,
        str_taker: None,
        current_fn: 0,
        cand_sig: None,
        pool_left: ARG_POOL_BYTES,
    };
    for (v, t) in init.iter_mut().zip(var_types.iter()) {
        *v = g.lit(*t);
    }
    let mut arr_init = [0i64; ALEN];
    for v in arr_init.iter_mut() {
        *v = g.lit(base);
    }
    let mut field_init = [0i64; SFIELDS];
    for v in field_init.iter_mut() {
        *v = g.lit(base);
    }
    let mut afield_init = [0i64; AFLEN];
    for v in afield_init.iter_mut() {
        *v = g.lit(base);
    }
    let mut nested_init = [0i64; NESTED];
    for v in nested_init.iter_mut() {
        *v = g.lit(base);
    }
    let mut konst = [0i64; ALEN];
    for v in konst.iter_mut() {
        *v = g.lit(base);
    }

    // Decide the table before the functions, since it constrains the shape of
    // the highest-numbered ones. Two entries is the smallest table where which
    // one runs is a real question; three occasionally, to keep a wrong index
    // from landing on the right answer by having nowhere else to land.
    let vtable = match g.rng.below(100) {
        0..=54 => 0,
        55..=84 => 2,
        _ => 3,
    };
    let count = vtable + g.rng.below(3) as usize;
    g.vtable = vtable;
    // One signature for every candidate, since they sit in one array.
    g.cand_sig = (vtable > 0).then(|| (g.pair.pick(g.rng), g.pair.pick(g.rng)));

    // The aggregates are `main`'s locals and affect only `main`'s body, but a
    // slice can also arrive as `f0`'s parameter — so both are decided before
    // the functions are generated, and only the slice decision reaches them.
    let aggregates = g.rng.below(100) < 60;

    // Slices view the `const` table, so they exist only where it does. Not in
    // every such program: a slice changes how `main`'s frame is laid out, and
    // the shapes without one have to keep being generated.
    let slices: Vec<(usize, usize)> = if aggregates && g.rng.below(100) < 55 {
        (0..SLICES).map(|_| gen_range(&mut g)).collect()
    } else {
        Vec::new()
    };
    // The two ranges `mk` chooses between, so a slice can arrive from a call
    // as well as from a range expression or another slice.
    let mk_ranges: Vec<(usize, usize)> = if slices.is_empty() {
        Vec::new()
    } else {
        (0..2).map(|_| gen_range(&mut g)).collect()
    };
    g.allow_slices = !slices.is_empty();
    // The two structs `mks` chooses between, so a struct can arrive from a
    // call as well as from a declaration.
    let mks: Vec<([i64; SFIELDS], [i64; AFLEN], [i64; NESTED])> = if aggregates {
        (0..2)
            .map(|_| {
                let mut fs = [0i64; SFIELDS];
                for v in fs.iter_mut() {
                    *v = g.lit(base);
                }
                let mut a = [0i64; AFLEN];
                for v in a.iter_mut() {
                    *v = g.lit(base);
                }
                let mut n = [0i64; NESTED];
                for v in n.iter_mut() {
                    *v = g.lit(base);
                }
                (fs, a, n)
            })
            .collect()
    } else {
        Vec::new()
    };
    // The pointer `main` declares. Its type is one half of the pair, so both
    // widths get a turn; its targets are the variables of that type, which is
    // never empty because both halves always appear among them.
    //
    // Half the programs, because a program without one still has to be
    // generated: taking a local's address is what forces it into memory, and
    // the shapes that never do have their own bugs.
    let has_pp_roll = g.rng.below(100) < 50;
    let ptr: Option<(Ty, PtrTarget)> = (g.rng.below(100) < 50).then(|| {
        let pt = g.pair.pick(g.rng);
        let mut targets: Vec<PtrTarget> = (0..VARS)
            .filter(|i| var_types[*i] == pt)
            .map(PtrTarget::Var)
            .collect();
        // At the aggregate type, `&s.f0` and `&arr[k]` are addresses the
        // pointer can equally hold — the struct field forces the struct into
        // memory at an offset, the element is the address computation with a
        // bug history. Added to the candidate set so `*p` may name any of them
        // and `Repoint` may move between kinds.
        if pt == base && aggregates {
            targets.extend((0..SFIELDS).map(PtrTarget::Field));
            targets.extend((0..ALEN).map(PtrTarget::Elem));
        }
        let k = g.rng.below(targets.len() as u64) as usize;
        (pt, targets[k].clone())
    });
    // `pk` writes one field of `main`'s struct through a `&S` and returns
    // another. Half the programs that have a struct at all.
    let poke: Option<(usize, usize)> = (aggregates && g.rng.below(100) < 50).then(|| {
        (
            g.rng.below(SFIELDS as u64) as usize,
            g.rng.below(SFIELDS as u64) as usize,
        )
    });
    // `bp` writes one of `main`'s variables through a `&T` parameter. It needs
    // a base-typed variable to point at and one to receive the return; both
    // come from the same set, so one is enough.
    let pass_ptr = (0..VARS).any(|i| var_types[i] == base) && g.rng.below(100) < 40;
    let struct_init_from_call =
        (!mks.is_empty() && g.rng.below(100) < 30).then(|| g.rng.below(2) as usize);
    // Decided here too, and for the same reason: `f0` may take the struct as a
    // parameter, so the functions have to be generated knowing whether there
    // is one. The per-function loop saves and restores this, so it still reads
    // `aggregates` by the time `main`'s body is generated.
    g.allow_fields = aggregates;
    // The enum is its own decision, independent of the aggregates: it is a
    // separate lowering — a two-byte value with its high byte in X, spelled
    // `Named` like a struct — and programs without one have to keep being
    // generated.
    let enum_init: Option<usize> =
        (g.rng.below(100) < 50).then(|| g.rng.below(EVARIANTS as u64) as usize);
    // A payload variant carries the pair's wide type two programs in five, so the
    // two-byte extraction (A:X, cast down) is exercised alongside the one-byte one.
    let enum_payload_wide = enum_init.is_some_and(|k| k > 0) && g.rng.below(100) < 40;
    let payload_ty = if enum_payload_wide { pair.wide } else { Ty::U8 };
    let enum_payload = g.lit(payload_ty);
    g.allow_enum = enum_init.is_some();
    // And the string, independently again. `str` is its own spelling in the
    // type table — not `Named`, not a primitive — and is the kind two of the
    // width lists had left out.
    let str_init: Option<usize> =
        (g.rng.below(100) < 50).then(|| g.rng.below(STRINGS.len() as u64) as usize);
    g.allow_str = str_init.is_some();
    g.str_len = str_init.map_or(0, |k| STRINGS[k].len());

    // A cycle of two, when there are two non-candidate functions to make one
    // from. It is the two highest-numbered of them, which is also where the
    // self-recursive function would have gone — a function gets one cycle or
    // the other, never both.
    let plain = count - vtable;
    let mutual = (plain >= 2 && g.rng.below(100) < 40).then(|| (plain - 2, plain - 1));
    let funcs = gen_funcs(&mut g, count, mutual);
    g.callable = 0..count;
    g.allow_indirect = vtable > 0;
    g.allow_aggregates = aggregates;
    // Set *after* the functions are generated, not before: `main` is the only
    // scope that can name the pointer — it is `main`'s local, and a function
    // body has no way to spell it — so a function generated while this was set
    // produced `*p` with no `p` in scope.
    let has_pp = ptr.is_some() && has_pp_roll;
    if let Some((pt, _)) = &ptr {
        g.ptr_ty = *pt;
        g.allow_pp = has_pp;
        g.ptr_targets = (0..VARS)
            .filter(|i| var_types[*i] == *pt)
            .map(PtrTarget::Var)
            .collect();
        if *pt == base && aggregates {
            g.ptr_targets.extend((0..SFIELDS).map(PtrTarget::Field));
            g.ptr_targets.extend((0..ALEN).map(PtrTarget::Elem));
        }
    }
    if poke.is_some() {
        g.poke_targets = (0..VARS).filter(|i| var_types[*i] == base).collect();
    }
    if pass_ptr {
        g.allow_pass_ptr = true;
        g.bp_targets = (0..VARS).filter(|i| var_types[*i] == base).collect();
    }
    g.main_slices = slices.len();
    // `f0` is the only function that can take a slice, and only when it exists
    // and is not one of the table's candidates.
    g.slice_taker = (count > vtable && funcs[0].slice_param).then_some(0);
    // Same rule for the struct, and it needs `main` to actually declare one.
    g.struct_taker = (aggregates && count > vtable && funcs[0].struct_param).then_some(0);
    g.enum_taker = (enum_init.is_some() && count > vtable && funcs[0].enum_param).then_some(0);
    g.str_taker = (str_init.is_some() && count > vtable && funcs[0].str_param).then_some(0);

    let n = 2 + g.rng.below(3) as usize;
    let mut stmts: Vec<S> = (0..n).flat_map(|_| gen_stmt_seq(&mut g, 2)).collect();

    // A mutable `static` in RAM (BSS), read and written in `main`. Exercises the
    // whole storage class the const table never reaches: BSS allocation, the
    // reset handler's initialiser write, and — the point after the recent
    // codegen work — a store, a read-modify-write, and the 16-bit INC/DEC fast
    // path all against an *absolute* address rather than a zero-page frame slot.
    // Two statements at the end so its final value is deterministic: a plain
    // store, then an RMW that reads the static back through `E::GLoad`.
    let mut_static = (g.rng.below(100) < 45).then(|| {
        let init = narrow(g.rng.below(0x1_0000) as i64, base);
        stmts.push(S::GStore(gen_arg(&mut g, base, 3)));
        let op = if g.rng.below(2) == 0 {
            Op::Add
        } else {
            Op::Sub
        };
        // Half the RMWs step by a literal 1 — the INC/DEC path — and half by a
        // computed value, which stores a 16-bit result to the absolute address.
        // A `Bin` operand must be at the base type with no widening, so this is
        // `gen_expr` (a same-type expression) rather than `gen_arg` (a boundary
        // value that may carry an `At` widening the two operands could not share).
        let step = if g.rng.below(2) == 0 {
            E::Lit(1)
        } else {
            gen_expr(&mut g, base, 1, false)
        };
        stmts.push(S::GStore(E::Bin(Box::new(E::GLoad), op, Box::new(step))));
        init
    });

    // An integer `match` in `main`: a scrutinee at the base type dispatched over
    // disjoint literal arms or one range arm, plus a wildcard default. Range
    // patterns on a 16-bit base drive the comparison-chain path that historically
    // mis-lowered, so this earns its place beside the arithmetic cases. Appended
    // before the counter/loop capture so any counters or loops the arm bodies
    // introduce are recorded.
    if g.rng.below(100) < 30 {
        let m = gen_int_match(&mut g, 2);
        stmts.push(m);
    }

    let (counters, loops) = (g.counters, g.loops);
    Prog {
        pair,
        base,
        var_types,
        init,
        counters,
        stmts,
        loops,
        funcs,
        aggregates,
        arr_init,
        field_init,
        afield_init,
        nested_init,
        enum_init,
        enum_payload,
        enum_payload_wide,
        str_init,
        konst,
        vtable,
        slices,
        mk_ranges,
        mks,
        poke,
        pass_ptr,
        has_pp,
        ptr,
        struct_init_from_call,
        mutual,
        mut_static,
    }
}

