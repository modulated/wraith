/// The name of a `for` induction variable.
///
/// `lv` rather than `i`, because `i8` and `i16` are type names and not
/// identifiers: a program with nine loops declared `for i8 in …`, which the
/// parser rejected. Every site that names a loop variable goes through here so
/// the rule has one place to hold.
fn loop_var(id: usize) -> String {
    format!("lv{id}")
}

fn render_index(ix: &Ix) -> String {
    match ix {
        Ix::Lit(k) => format!("{k}"),
        Ix::Loop(id) => loop_var(*id),
        Ix::Wrapped(i) => format!("((v{i} as u8) % {ALEN})"),
    }
}

fn render_place(p: &Place, sc: Scope) -> String {
    match p {
        Place::Var(v) => sc.var(*v),
        Place::Elem(ix) => format!("arr[{}]", render_index(ix)),
        Place::Field(f) => format!("s.f{f}"),
    }
}

fn render(e: &E, ty: Ty, sc: Scope) -> String {
    match e {
        E::Lit(v) if *v < 0 => format!("({v})"),
        E::Lit(v) => format!("{v}"),
        E::Var(i) => sc.var(*i),
        E::Loop(id) if ty == Ty::U8 => loop_var(*id),
        E::Loop(id) => format!("({} as {})", loop_var(*id), ty.name()),
        E::Bin(l, op, r) => format!("({} {} {})", render(l, ty, sc), op.sym(), render(r, ty, sc)),
        E::Cast(to, inner) => format!(
            "(({} as {}) as {})",
            render(inner, ty, sc),
            to.name(),
            ty.name()
        ),
        E::Call { id, budget, args } => {
            let mut parts: Vec<String> = Vec::new();
            if let Some(b) = budget {
                parts.push(b.to_string());
            }
            parts.extend(args.iter().map(|a| render(a, ty, sc)));
            format!("f{id}({})", parts.join(", "))
        }
        E::SelfCall(arg) => {
            let Scope::Func { id, .. } = sc else {
                unreachable!("a self-call outside a function")
            };
            format!("f{id}(d - 1, {})", render(arg, ty, sc))
        }
        E::Elem(ix) => format!("arr[{}]", render_index(ix)),
        E::Konst(ix) => format!("TBL[{}]", render_index(ix)),
        E::Field(f) => format!("s.f{f}"),
    }
}

fn render_bool(b: &B, ty: Ty, sc: Scope) -> String {
    match b {
        B::Rel(l, c, r) => format!("({} {} {})", render(l, ty, sc), c.sym(), render(r, ty, sc)),
        B::And(l, r) => format!("({} && {})", render_bool(l, ty, sc), render_bool(r, ty, sc)),
        B::Or(l, r) => format!("({} || {})", render_bool(l, ty, sc), render_bool(r, ty, sc)),
        B::Not(inner) => format!("(!{})", render_bool(inner, ty, sc)),
    }
}

fn render_stmts(stmts: &[S], ty: Ty, indent: usize, sc: Scope) -> String {
    let pad = " ".repeat(indent);
    let mut out = String::new();
    for s in stmts {
        match s {
            S::Assign(place, e) => out.push_str(&format!(
                "{pad}{} = {};\n",
                render_place(place, sc),
                render(e, ty, sc)
            )),
            S::If(c, then, otherwise) => {
                out.push_str(&format!("{pad}if {} {{\n", render_bool(c, ty, sc)));
                out.push_str(&render_stmts(then, ty, indent + 4, sc));
                match otherwise {
                    Some(e) => {
                        out.push_str(&format!("{pad}}} else {{\n"));
                        out.push_str(&render_stmts(e, ty, indent + 4, sc));
                        out.push_str(&format!("{pad}}}\n"));
                    }
                    None => out.push_str(&format!("{pad}}}\n")),
                }
            }
            S::For(id, count, body) => {
                out.push_str(&format!("{pad}for {} in 0..{count} {{\n", loop_var(*id)));
                out.push_str(&render_stmts(body, ty, indent + 4, sc));
                out.push_str(&format!("{pad}}}\n"));
            }
            S::While(id, body) => {
                out.push_str(&format!("{pad}while c{id} > 0 {{\n"));
                out.push_str(&render_stmts(body, ty, indent + 4, sc));
                out.push_str(&format!("{pad}    c{id} = c{id} - 1;\n"));
                out.push_str(&format!("{pad}}}\n"));
            }
        }
    }
    out
}

/// One generated function, declarations and all.
fn render_func(p: &Prog, id: usize) -> String {
    let f = &p.funcs[id];
    let ty = p.ty;
    let tn = ty.name();
    let sc = Scope::Func {
        id,
        params: f.params,
    };

    let mut params: Vec<String> = Vec::new();
    if f.recursive {
        params.push("d: u8".to_string());
    }
    for i in 0..f.params {
        params.push(format!("p{i}: {tn}"));
    }

    let mut out = format!("fn f{id}({}) -> {tn} {{\n", params.join(", "));
    for (i, v) in f.local_init.iter().enumerate() {
        let lit = if *v < 0 {
            format!("({v})")
        } else {
            format!("{v}")
        };
        out.push_str(&format!("    let q{i}: {tn} = {lit};\n"));
    }
    if f.recursive {
        out.push_str(&format!(
            "    if d == 0 {{ return {}; }}\n",
            render(&f.base, ty, sc)
        ));
    }
    out.push_str(&render_stmts(&f.body, ty, 4, sc));
    out.push_str(&format!("    return {};\n}}\n", render(&f.ret, ty, sc)));
    out
}

/// The surface forms one program is written in. All must agree; each routes
/// through a different part of codegen.
#[derive(Clone, Copy, PartialEq, Debug)]
enum Form {
    /// Statements directly in `main`.
    Inline,
    /// The whole body in a called function.
    ViaFunction,
    /// The statements inside the taken arm of a `match`.
    ViaMatch,
    /// The statements inside a loop that runs exactly once.
    ViaLoop,
}

const FORMS: [Form; 4] = [
    Form::Inline,
    Form::ViaFunction,
    Form::ViaMatch,
    Form::ViaLoop,
];

/// The cells a program reports: its variables, then the array elements, then
/// the struct fields when it has them.
fn out_cells(p: &Prog) -> usize {
    VARS + if p.aggregates { ALEN + SFIELDS } else { 0 }
}

/// One output byte per 8-bit cell, two per 16-bit one.
fn out_bytes(p: &Prog) -> usize {
    out_cells(p) * if p.ty.wide() { 2 } else { 1 }
}

fn render_program(p: &Prog, form: Form) -> String {
    let ty = p.ty;
    let tn = ty.name();

    let head: String = (0..out_bytes(p))
        .map(|i| format!("const OUT{i}: addr = 0x{:04X};\n", 0x0900 + i))
        .collect();

    // The struct type is declared at the top level, so it exists whether or not
    // this program's `main` uses one.
    let lit = |v: &i64| -> String {
        if *v < 0 {
            format!("({v})")
        } else {
            format!("{v}")
        }
    };
    let struct_decl = if p.aggregates {
        let fields: Vec<String> = (0..SFIELDS).map(|i| format!("f{i}: {tn}")).collect();
        let table: Vec<String> = p.konst.iter().map(lit).collect();
        format!(
            "struct S {{ {} }}\nconst TBL: [{tn}; {ALEN}] = [{}];\n",
            fields.join(", "),
            table.join(", ")
        )
    } else {
        String::new()
    };

    // Generated functions come before `main` in every surface form: they are
    // what the body calls, and their frames are what the call-graph colouring
    // has to keep apart from it.
    let funcs: String = (0..p.funcs.len()).map(|i| render_func(p, i)).collect();

    let mut decls = String::new();
    for (i, v) in p.init.iter().enumerate() {
        let lit = if *v < 0 {
            format!("({v})")
        } else {
            format!("{v}")
        };
        decls.push_str(&format!("    let v{i}: {tn} = {lit};\n"));
    }
    for (i, c) in p.counters.iter().enumerate() {
        decls.push_str(&format!("    let c{i}: u8 = {c};\n"));
    }
    if p.aggregates {
        let elems: Vec<String> = p.arr_init.iter().map(lit).collect();
        decls.push_str(&format!(
            "    let arr: [{tn}; {ALEN}] = [{}];\n",
            elems.join(", ")
        ));
        let fields: Vec<String> = p
            .field_init
            .iter()
            .enumerate()
            .map(|(i, v)| format!("f{i}: {}", lit(v)))
            .collect();
        decls.push_str(&format!("    let s: S = S {{ {} }};\n", fields.join(", ")));
    }

    // Every cell is written out, in the order `expected` reports them.
    let mut cells: Vec<String> = (0..VARS).map(|i| format!("v{i}")).collect();
    if p.aggregates {
        cells.extend((0..ALEN).map(|i| format!("arr[{i}]")));
        cells.extend((0..SFIELDS).map(|i| format!("s.f{i}")));
    }

    let mut stores = String::new();
    for (i, cell) in cells.iter().enumerate() {
        if ty.wide() {
            let src = if ty.signed() {
                format!("{cell} as u16")
            } else {
                cell.clone()
            };
            stores.push_str(&format!("    let o{i}: u16 = {src};\n"));
            stores.push_str(&format!("    OUT{} = o{i}.low;\n", i * 2));
            stores.push_str(&format!("    OUT{} = o{i}.high;\n", i * 2 + 1));
        } else {
            let src = if ty.signed() {
                format!("{cell} as u8")
            } else {
                cell.clone()
            };
            stores.push_str(&format!("    OUT{i} = {src};\n"));
        }
    }

    // Re-indent a block of already-formatted statements by one more level.
    let bump = |s: &str| -> String { s.lines().map(|l| format!("    {l}\n")).collect::<String>() };

    let body = render_stmts(&p.stmts, ty, 4, Scope::Main);

    match form {
        Form::Inline => {
            format!(
                "{head}{struct_decl}{funcs}#[reset]\nfn main() {{\n{decls}{body}{stores}    loop {{}}\n}}\n"
            )
        }
        Form::ViaFunction => format!(
            "{head}{struct_decl}{funcs}fn body() {{\n{decls}{body}{stores}}}\n\
             #[reset]\nfn main() {{\n    body();\n    loop {{}}\n}}\n"
        ),
        Form::ViaMatch => format!(
            "{head}{struct_decl}{funcs}#[reset]\nfn main() {{\n{decls}    let sel: u8 = 0;\n\
                 match sel {{\n        0 => {{\n{}{}        }}\n        _ => {{}}\n    }}\n\
             \x20   loop {{}}\n}}\n",
            bump(&bump(&body)),
            bump(&bump(&stores)),
        ),
        Form::ViaLoop => format!(
            "{head}{struct_decl}{funcs}#[reset]\nfn main() {{\n{decls}    for w0 in 0..1 {{\n{}{}    }}\n\
             \x20   loop {{}}\n}}\n",
            bump(&body),
            bump(&stores),
        ),
    }
}

