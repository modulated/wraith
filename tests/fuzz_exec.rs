    type Seen = BTreeSet<String>;

    fn note(seen: &mut Seen, group: &str, variant: &str) {
        seen.insert(format!("{group}::{variant}"));
    }

    fn w_item(item: &Item, s: &mut Seen) {
        match item {
            Item::Function(f) => {
                note(s, "Item", "Function");
                if let Some(t) = &f.return_type {
                    w_type(&t.node, s);
                }
                for p in &f.params {
                    w_type(&p.ty.node, s);
                }
                w_stmt(&f.body.node, s);
            }
            Item::Struct(_) => note(s, "Item", "Struct"),
            Item::Enum(_) => note(s, "Item", "Enum"),
            Item::Static(st) => {
                note(s, "Item", "Static");
                w_type(&st.ty.node, s);
                w_expr(&st.init.node, s);
            }
            Item::Address(a) => {
                note(s, "Item", "Address");
                w_expr(&a.address.node, s);
            }
            Item::Import(_) => note(s, "Item", "Import"),
        }
    }

    fn w_stmt(stmt: &Stmt, s: &mut Seen) {
        match stmt {
            Stmt::VarDecl { ty, init, .. } => {
                note(s, "Stmt", "VarDecl");
                w_type(&ty.node, s);
                w_expr(&init.node, s);
            }
            Stmt::Assign { target, value } => {
                note(s, "Stmt", "Assign");
                w_expr(&target.node, s);
                w_expr(&value.node, s);
            }
            Stmt::Expr(e) => {
                note(s, "Stmt", "Expr");
                w_expr(&e.node, s);
            }
            Stmt::Return(e) => {
                note(s, "Stmt", "Return");
                if let Some(e) = e {
                    w_expr(&e.node, s);
                }
            }
            Stmt::If {
                condition,
                then_branch,
                else_branch,
            } => {
                note(s, "Stmt", "If");
                w_expr(&condition.node, s);
                w_stmt(&then_branch.node, s);
                if let Some(e) = else_branch {
                    w_stmt(&e.node, s);
                }
            }
            Stmt::While { condition, body } => {
                note(s, "Stmt", "While");
                w_expr(&condition.node, s);
                w_stmt(&body.node, s);
            }
            Stmt::Loop { body } => {
                note(s, "Stmt", "Loop");
                w_stmt(&body.node, s);
            }
            Stmt::For {
                var_type,
                range,
                body,
                ..
            } => {
                note(s, "Stmt", "For");
                if let Some(t) = var_type {
                    w_type(&t.node, s);
                }
                w_expr(&range.start.node, s);
                w_expr(&range.end.node, s);
                w_stmt(&body.node, s);
            }
            Stmt::ForEach {
                var_type,
                iterable,
                body,
                ..
            } => {
                note(s, "Stmt", "ForEach");
                if let Some(t) = var_type {
                    w_type(&t.node, s);
                }
                w_expr(&iterable.node, s);
                w_stmt(&body.node, s);
            }
            Stmt::Match { expr, arms } => {
                note(s, "Stmt", "Match");
                w_expr(&expr.node, s);
                for arm in arms {
                    w_pattern(&arm.pattern.node, s);
                    w_stmt(&arm.body.node, s);
                }
            }
            Stmt::Break => note(s, "Stmt", "Break"),
            Stmt::Continue => note(s, "Stmt", "Continue"),
            Stmt::Block(body) => {
                note(s, "Stmt", "Block");
                for st in body {
                    w_stmt(&st.node, s);
                }
            }
            Stmt::Asm { .. } => note(s, "Stmt", "Asm"),
        }
    }

    fn w_expr(expr: &Expr, s: &mut Seen) {
        match expr {
            Expr::Literal(lit) => {
                note(s, "Expr", "Literal");
                w_literal(lit, s);
            }
            Expr::Variable(_) => note(s, "Expr", "Variable"),
            Expr::Binary { left, op, right } => {
                note(s, "Expr", "Binary");
                note(s, "BinaryOp", &format!("{op:?}"));
                w_expr(&left.node, s);
                w_expr(&right.node, s);
            }
            Expr::Unary { op, operand } => {
                note(s, "Expr", "Unary");
                note(s, "UnaryOp", &format!("{op:?}"));
                w_expr(&operand.node, s);
            }
            Expr::Cast { expr, target_type } => {
                note(s, "Expr", "Cast");
                w_type(&target_type.node, s);
                w_expr(&expr.node, s);
            }
            Expr::Field { object, .. } => {
                note(s, "Expr", "Field");
                w_expr(&object.node, s);
            }
            Expr::Index { object, index } => {
                note(s, "Expr", "Index");
                w_expr(&object.node, s);
                w_expr(&index.node, s);
            }
            Expr::Slice {
                object, start, end, ..
            } => {
                note(s, "Expr", "Slice");
                w_expr(&object.node, s);
                w_expr(&start.node, s);
                w_expr(&end.node, s);
            }
            Expr::Call { args, .. } => {
                note(s, "Expr", "Call");
                for a in args {
                    w_expr(&a.node, s);
                }
            }
            Expr::CallIndirect { callee, args } => {
                note(s, "Expr", "CallIndirect");
                w_expr(&callee.node, s);
                for a in args {
                    w_expr(&a.node, s);
                }
            }
            Expr::StructInit { fields, .. } => {
                note(s, "Expr", "StructInit");
                for f in fields {
                    w_expr(&f.value.node, s);
                }
            }
            Expr::AnonStructInit { fields } => {
                note(s, "Expr", "AnonStructInit");
                for f in fields {
                    w_expr(&f.value.node, s);
                }
            }
            Expr::EnumVariant { .. } => note(s, "Expr", "EnumVariant"),
            Expr::SliceLen(inner) => {
                note(s, "Expr", "SliceLen");
                w_expr(&inner.node, s);
            }
            Expr::U16Low(inner) => {
                note(s, "Expr", "U16Low");
                w_expr(&inner.node, s);
            }
            Expr::U16High(inner) => {
                note(s, "Expr", "U16High");
                w_expr(&inner.node, s);
            }
            Expr::CpuFlagCarry => note(s, "Expr", "CpuFlagCarry"),
            Expr::CpuFlagZero => note(s, "Expr", "CpuFlagZero"),
            Expr::CpuFlagOverflow => note(s, "Expr", "CpuFlagOverflow"),
            Expr::CpuFlagNegative => note(s, "Expr", "CpuFlagNegative"),
            Expr::Paren(inner) => {
                note(s, "Expr", "Paren");
                w_expr(&inner.node, s);
            }
            Expr::Match { expr, arms } => {
                note(s, "Expr", "Match");
                w_expr(&expr.node, s);
                for arm in arms {
                    w_pattern(&arm.pattern.node, s);
                    w_expr(&arm.body.node, s);
                }
            }
            Expr::BitOp { object, bit, .. } => {
                note(s, "Expr", "BitOp");
                w_expr(&object.node, s);
                w_expr(&bit.node, s);
            }
        }
    }

    fn w_literal(lit: &Literal, s: &mut Seen) {
        match lit {
            Literal::Integer(_) => note(s, "Literal", "Integer"),
            Literal::Bool(_) => note(s, "Literal", "Bool"),
            Literal::Char(_) => note(s, "Literal", "Char"),
            Literal::String(_) => note(s, "Literal", "String"),
            Literal::Array(elems) => {
                note(s, "Literal", "Array");
                for e in elems {
                    w_expr(&e.node, s);
                }
            }
            Literal::ArrayFill { .. } => note(s, "Literal", "ArrayFill"),
        }
    }

    fn w_pattern(p: &Pattern, s: &mut Seen) {
        match p {
            Pattern::Literal(e) => {
                note(s, "Pattern", "Literal");
                w_expr(&e.node, s);
            }
            Pattern::Range { start, end, .. } => {
                note(s, "Pattern", "Range");
                w_expr(&start.node, s);
                w_expr(&end.node, s);
            }
            Pattern::Wildcard => note(s, "Pattern", "Wildcard"),
            Pattern::EnumVariant { .. } => note(s, "Pattern", "EnumVariant"),
            Pattern::Variable(_) => note(s, "Pattern", "Variable"),
        }
    }

    fn w_type(t: &TypeExpr, s: &mut Seen) {
        match t {
            TypeExpr::Primitive(p) => {
                note(s, "TypeExpr", "Primitive");
                note(s, "PrimitiveType", &format!("{p:?}"));
            }
            TypeExpr::Named(_) => note(s, "TypeExpr", "Named"),
            TypeExpr::StringBuf { .. } => note(s, "TypeExpr", "StringBuf"),
            TypeExpr::Array { element, .. } => {
                note(s, "TypeExpr", "Array");
                w_type(&element.node, s);
            }
            TypeExpr::Slice { element } => {
                note(s, "TypeExpr", "Slice");
                w_type(&element.node, s);
            }
            TypeExpr::Pointer { pointee } => {
                note(s, "TypeExpr", "Pointer");
                w_type(&pointee.node, s);
            }
            TypeExpr::Function { params, ret } => {
                note(s, "TypeExpr", "Function");
                for p in params {
                    w_type(&p.node, s);
                }
                if let Some(r) = ret {
                    w_type(&r.node, s);
                }
            }
        }
    }

