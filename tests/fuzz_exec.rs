// The oracle: run the same tree in Rust
// ---------------------------------------------------------------------------

struct St<'a> {
    prog: &'a Prog,
    vars: Vec<i64>,
    /// `main`'s array and struct. Empty inside a function, which cannot name
    /// them, and in a program that declares neither.
    arr: Vec<i64>,
    fields: Vec<i64>,
    counters: Vec<i64>,
    loops: Vec<i64>,
    /// The function being executed and its remaining budget, for a self-call.
    /// `None` in `main`, where no self-call can appear.
    current: Option<(usize, i64)>,
}

/// Call a generated function. Its locals are fresh per invocation — which is
/// what the compiler's frame save/restore has to reproduce across a recursive
/// call — and it reads nothing but its own scope, so no caller state is passed.
fn call_fn(p: &Prog, id: usize, budget: i64, args: &[i64], ty: Ty) -> i64 {
    let f = &p.funcs[id];
    let mut vars: Vec<i64> = args.to_vec();
    vars.extend(f.local_init.iter().map(|v| narrow(*v, ty)));
    let mut st = St {
        prog: p,
        vars,
        // A function names no aggregate, so there is nothing to carry in.
        arr: Vec::new(),
        fields: Vec::new(),
        // Function bodies contain no loops, so these are never indexed; sized
        // rather than empty so a generator change cannot panic here.
        counters: p.counters.iter().map(|c| *c as i64).collect(),
        loops: vec![0; p.loops],
        current: Some((id, budget)),
    };
    if f.recursive && budget == 0 {
        return eval(&f.base, &st, ty);
    }
    exec(&f.body, &mut st, ty);
    eval(&f.ret, &st, ty)
}

fn eval(e: &E, st: &St, ty: Ty) -> i64 {
    match e {
        E::Lit(v) => narrow(*v, ty),
        E::Var(i) => st.vars[*i],
        E::Loop(id) => narrow(st.loops[*id], ty),
        E::Cast(to, inner) => narrow(narrow(eval(inner, st, ty), *to), ty),
        E::Call { id, budget, args } => {
            let vals: Vec<i64> = args.iter().map(|a| eval(a, st, ty)).collect();
            narrow(
                call_fn(st.prog, *id, budget.unwrap_or(0) as i64, &vals, ty),
                ty,
            )
        }
        E::SelfCall(arg) => {
            let (id, budget) = st.current.expect("a self-call outside a function");
            let v = eval(arg, st, ty);
            narrow(call_fn(st.prog, id, budget - 1, &[v], ty), ty)
        }
        E::Elem(ix) => st.arr[eval_index(ix, st, ty)],
        E::Konst(ix) => narrow(st.prog.konst[eval_index(ix, st, ty)], ty),
        E::Field(i) => st.fields[*i],
        E::Bin(l, op, r) => {
            let a = eval(l, st, ty);
            let b = eval(r, st, ty);
            let v = match op {
                Op::Add => a.wrapping_add(b),
                Op::Sub => a.wrapping_sub(b),
                Op::Mul => a.wrapping_mul(b),
                // Generated divisors are positive literals; the guard is
                // belt-and-braces so a generator change cannot panic here.
                Op::Div => a / if b == 0 { 1 } else { b },
                Op::Rem => a % if b == 0 { 1 } else { b },
                // Bitwise operators act on the value's bit pattern, so a
                // negative operand has to be seen unsigned first.
                Op::And => (raw(a, ty) & raw(b, ty)) as i64,
                Op::Or => (raw(a, ty) | raw(b, ty)) as i64,
                Op::Xor => (raw(a, ty) ^ raw(b, ty)) as i64,
                Op::Shl => a << b.clamp(0, ty.bits() as i64 - 1),
                // `>>` on a signed type is arithmetic, which is what Rust's
                // `>>` on `i64` already does for our sign-correct values.
                Op::Shr => a >> b.clamp(0, ty.bits() as i64 - 1),
            };
            narrow(v, ty)
        }
    }
}

/// Where an index lands. Mirrors the three forms the generator emits, each of
/// which is in range by construction.
fn eval_index(ix: &Ix, st: &St, ty: Ty) -> usize {
    match ix {
        Ix::Lit(k) => *k,
        Ix::Loop(id) => st.loops[*id] as usize,
        // `(v as u8) % LEN`: the cast keeps the low byte, whatever the type.
        Ix::Wrapped(i) => (raw(st.vars[*i], ty) as usize & 0xFF) % ALEN,
    }
}

fn eval_bool(b: &B, st: &St, ty: Ty) -> bool {
    match b {
        B::Rel(l, c, r) => c.apply(eval(l, st, ty), eval(r, st, ty)),
        B::And(l, r) => eval_bool(l, st, ty) && eval_bool(r, st, ty),
        B::Or(l, r) => eval_bool(l, st, ty) || eval_bool(r, st, ty),
        B::Not(inner) => !eval_bool(inner, st, ty),
    }
}

fn exec(stmts: &[S], st: &mut St, ty: Ty) {
    for s in stmts {
        match s {
            S::Assign(place, e) => {
                let value = eval(e, st, ty);
                match place {
                    Place::Var(v) => st.vars[*v] = value,
                    Place::Elem(ix) => {
                        let k = eval_index(ix, st, ty);
                        st.arr[k] = value;
                    }
                    Place::Field(f) => st.fields[*f] = value,
                }
            }
            S::If(c, then, otherwise) => {
                if eval_bool(c, st, ty) {
                    exec(then, st, ty);
                } else if let Some(e) = otherwise {
                    exec(e, st, ty);
                }
            }
            S::For(id, count, body) => {
                for i in 0..*count as i64 {
                    st.loops[*id] = i;
                    exec(body, st, ty);
                }
            }
            S::While(id, body) => {
                while st.counters[*id] > 0 {
                    exec(body, st, ty);
                    st.counters[*id] -= 1;
                }
            }
        }
    }
}

/// The final bit pattern of every program variable.
fn expected(p: &Prog) -> Vec<u32> {
    let narrowed = |xs: &[i64]| -> Vec<i64> { xs.iter().map(|v| narrow(*v, p.ty)).collect() };
    let mut st = St {
        prog: p,
        vars: narrowed(&p.init),
        arr: if p.aggregates {
            narrowed(&p.arr_init)
        } else {
            Vec::new()
        },
        fields: if p.aggregates {
            narrowed(&p.field_init)
        } else {
            Vec::new()
        },
        counters: p.counters.iter().map(|c| *c as i64).collect(),
        loops: vec![0; p.loops],
        current: None,
    };
    exec(&p.stmts, &mut st, p.ty);
    st.vars
        .iter()
        .chain(st.arr.iter())
        .chain(st.fields.iter())
        .map(|v| raw(*v, p.ty))
        .collect()
}

