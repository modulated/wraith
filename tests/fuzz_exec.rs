/// Compile and run one program, reading back every variable, or reporting the
/// reason it did not get there.
fn observe(src: &str, p: &Prog) -> Result<Vec<u32>, String> {
    let (ty, cells) = (p.ty, out_cells(p));
    let res = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        let mut e = run(src);
        (0..cells)
            .map(|i| {
                if ty.wide() {
                    e.mem16(0x0900 + (i * 2) as u16) as u32
                } else {
                    e.mem(0x0900 + i as u16) as u32
                }
            })
            .collect::<Vec<u32>>()
    }));
    res.map_err(|p| {
        p.downcast_ref::<String>()
            .cloned()
            .or_else(|| p.downcast_ref::<&str>().map(|s| s.to_string()))
            .unwrap_or_else(|| "<panic>".into())
            .lines()
            .take(3)
            .collect::<Vec<_>>()
            .join(" | ")
    })
}

fn iterations() -> u64 {
    std::env::var("WRAITH_FUZZ_ITERS")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(120)
}

/// Why a program failed. Shrinking has to preserve the *kind*: a reduction
/// that turns a wrong answer into a rejected program has found a different bug
/// and would report the wrong one.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Kind {
    /// Ran, and produced values the oracle disagrees with.
    WrongAnswer,
    /// Never ran — rejected by the compiler, the assembler, or the emulator.
    Rejected,
}

/// How this program disagrees with the oracle in one surface form, if it does.
fn disagrees_as(p: &Prog, form: Form) -> Option<(Kind, String)> {
    let want = expected(p);
    match observe(&render_program(p, form), p) {
        Ok(got) if got == want => None,
        Ok(got) => Some((
            Kind::WrongAnswer,
            format!("gave {got:?}, expected {want:?}"),
        )),
        Err(why) => Some((Kind::Rejected, format!("failed to run: {why}"))),
    }
}

/// The first surface form that disagrees, if any.
fn disagrees(p: &Prog) -> Option<(Form, Kind, String)> {
    FORMS
        .into_iter()
        .find_map(|f| disagrees_as(p, f).map(|(k, why)| (f, k, why)))
}

// ---------------------------------------------------------------------------
// Shrinking
// ---------------------------------------------------------------------------
//
// A generated program is 30-odd lines of dense arithmetic, and the part of it
// that matters is usually one operator. Reducing it before reporting is the
// difference between a finding a person can act on and one they have to
// re-derive by hand. Every candidate is re-run, so whatever survives still
// fails for the same reason it did before.

/// Apply the `target`-th available simplification, counting them in `seen`.
/// With a `target` no index can reach, this only counts.
fn mutate(p: &mut Prog, target: usize, seen: &mut usize) -> bool {
    for i in 0..VARS {
        if p.init[i] != 0 {
            if *seen == target {
                p.init[i] = 0;
                return true;
            }
            *seen += 1;
        }
    }
    for i in 0..p.counters.len() {
        if p.counters[i] > 1 {
            if *seen == target {
                p.counters[i] = 1;
                return true;
            }
            *seen += 1;
        }
    }
    // Dropping the recursion is the single most useful reduction for a
    // recursive function: what is left is an ordinary call. It also changes the
    // function's arity — the budget parameter goes with it — so every call site
    // has to stop passing one, or the reduced program does not compile.
    for i in 0..p.funcs.len() {
        if p.funcs[i].recursive {
            if *seen == target {
                p.funcs[i].recursive = false;
                strip_self_calls(&mut p.funcs[i].ret);
                drop_budgets(p, i);
                return true;
            }
            *seen += 1;
        }
    }
    for f in p.funcs.iter_mut() {
        for i in 0..f.local_init.len() {
            if f.local_init[i] != 0 {
                if *seen == target {
                    f.local_init[i] = 0;
                    return true;
                }
                *seen += 1;
            }
        }
        if mutate_block(&mut f.body, target, seen) {
            return true;
        }
        if mutate_expr(&mut f.ret, target, seen) {
            return true;
        }
        if mutate_expr(&mut f.base, target, seen) {
            return true;
        }
    }
    mutate_block(&mut p.stmts, target, seen)
}

/// Stop passing a recursion budget to `id`, everywhere in the program. Paired
/// with clearing the function's `recursive` flag, which removes the parameter
/// the budget was for.
fn drop_budgets(p: &mut Prog, id: usize) {
    fn in_expr(e: &mut E, id: usize) {
        match e {
            E::Call {
                id: callee,
                budget,
                args,
            } => {
                if *callee == id {
                    *budget = None;
                }
                for a in args {
                    in_expr(a, id);
                }
            }
            E::SelfCall(arg) => in_expr(arg, id),
            E::Bin(l, _, r) => {
                in_expr(l, id);
                in_expr(r, id);
            }
            E::Cast(_, inner) => in_expr(inner, id),
            _ => {}
        }
    }
    fn in_bool(b: &mut B, id: usize) {
        match b {
            B::Rel(l, _, r) => {
                in_expr(l, id);
                in_expr(r, id);
            }
            B::And(l, r) | B::Or(l, r) => {
                in_bool(l, id);
                in_bool(r, id);
            }
            B::Not(inner) => in_bool(inner, id),
        }
    }
    fn in_block(stmts: &mut [S], id: usize) {
        for s in stmts {
            match s {
                S::Assign(_, e) => in_expr(e, id),
                S::If(c, t, e) => {
                    in_bool(c, id);
                    in_block(t, id);
                    if let Some(e) = e {
                        in_block(e, id);
                    }
                }
                S::For(_, _, body) | S::While(_, body) => in_block(body, id),
            }
        }
    }
    for f in p.funcs.iter_mut() {
        in_block(&mut f.body, id);
        in_expr(&mut f.ret, id);
        in_expr(&mut f.base, id);
    }
    in_block(&mut p.stmts, id);
}

/// Replace every self-call with its argument. Used when a function stops being
/// recursive: a `SelfCall` in a non-recursive function has no `d` to decrement.
fn strip_self_calls(e: &mut E) {
    match e {
        E::SelfCall(arg) => {
            let lifted = (**arg).clone();
            *e = lifted;
            strip_self_calls(e);
        }
        E::Bin(l, _, r) => {
            strip_self_calls(l);
            strip_self_calls(r);
        }
        E::Cast(_, inner) => strip_self_calls(inner),
        E::Call { args, .. } => {
            for a in args {
                strip_self_calls(a);
            }
        }
        _ => {}
    }
}

fn mutate_block(block: &mut Vec<S>, target: usize, seen: &mut usize) -> bool {
    // Never empty a block: an enclosing statement gets dropped whole instead.
    if block.len() > 1 {
        for i in 0..block.len() {
            if *seen == target {
                block.remove(i);
                return true;
            }
            *seen += 1;
        }
    }
    for s in block.iter_mut() {
        if mutate_stmt(s, target, seen) {
            return true;
        }
    }
    false
}

/// Reduce an index to a constant 0 — the simplest in-range form.
fn mutate_index(ix: &mut Ix, target: usize, seen: &mut usize) -> bool {
    if matches!(ix, Ix::Lit(0)) {
        return false;
    }
    if *seen == target {
        *ix = Ix::Lit(0);
        return true;
    }
    *seen += 1;
    false
}

fn mutate_stmt(s: &mut S, target: usize, seen: &mut usize) -> bool {
    match s {
        S::Assign(place, e) => {
            // Storing to `v0` instead of an element or a field takes the index
            // and the aggregate out of the picture when neither is the cause.
            // Only for an element or a field: those occur in `main` alone,
            // where `v0` is assignable. Retargeting a `Var` is not safe — the
            // same index inside a function names a *parameter*, which is
            // immutable, and the reduced program stops compiling.
            if matches!(place, Place::Elem(_) | Place::Field(_)) {
                if *seen == target {
                    *place = Place::Var(0);
                    return true;
                }
                *seen += 1;
            }
            if let Place::Elem(ix) = place
                && mutate_index(ix, target, seen)
            {
                return true;
            }
            mutate_expr(e, target, seen)
        }
        S::If(cond, then, otherwise) => {
            if mutate_bool(cond, target, seen) {
                return true;
            }
            if otherwise.is_some() {
                if *seen == target {
                    *otherwise = None;
                    return true;
                }
                *seen += 1;
            }
            if mutate_block(then, target, seen) {
                return true;
            }
            match otherwise {
                Some(b) => mutate_block(b, target, seen),
                None => false,
            }
        }
        S::For(_, count, body) => {
            if *count > 1 {
                if *seen == target {
                    *count = 1;
                    return true;
                }
                *seen += 1;
            }
            mutate_block(body, target, seen)
        }
        S::While(_, body) => mutate_block(body, target, seen),
    }
}

fn mutate_expr(e: &mut E, target: usize, seen: &mut usize) -> bool {
    match e {
        E::Lit(v) => {
            if *v != 0 {
                if *seen == target {
                    *v = 0;
                    return true;
                }
                *seen += 1;
            }
            false
        }
        E::Cast(_, inner) => {
            if *seen == target {
                let lifted = (**inner).clone();
                *e = lifted;
                return true;
            }
            *seen += 1;
            mutate_expr(inner, target, seen)
        }
        E::SelfCall(arg) => {
            if *seen == target {
                let lifted = (**arg).clone();
                *e = lifted;
                return true;
            }
            *seen += 1;
            mutate_expr(arg, target, seen)
        }
        E::Elem(ix) | E::Konst(ix) => {
            if *seen == target {
                *e = E::Var(0);
                return true;
            }
            *seen += 1;
            mutate_index(ix, target, seen)
        }
        E::Field(_) => {
            if *seen == target {
                *e = E::Var(0);
                return true;
            }
            *seen += 1;
            false
        }
        E::Call { budget, args, .. } => {
            if let Some(b) = budget
                && *b > 0
            {
                if *seen == target {
                    *budget = Some(0);
                    return true;
                }
                *seen += 1;
            }
            for a in args.iter() {
                if *seen == target {
                    let lifted = a.clone();
                    *e = lifted;
                    return true;
                }
                *seen += 1;
            }
            let E::Call { args, .. } = e else {
                unreachable!()
            };
            for a in args.iter_mut() {
                if mutate_expr(a, target, seen) {
                    return true;
                }
            }
            false
        }
        E::Bin(l, op, r) => {
            if *seen == target {
                let lifted = (**l).clone();
                *e = lifted;
                return true;
            }
            *seen += 1;
            if *seen == target {
                let lifted = (**r).clone();
                *e = lifted;
                return true;
            }
            *seen += 1;
            let op = *op;
            if mutate_expr(l, target, seen) {
                return true;
            }
            // The divisor is a nonzero literal by construction, and zeroing it
            // would leave a program the oracle is not entitled to an answer for.
            if matches!(op, Op::Div | Op::Rem) {
                return false;
            }
            mutate_expr(r, target, seen)
        }
        _ => false,
    }
}

fn mutate_bool(b: &mut B, target: usize, seen: &mut usize) -> bool {
    match b {
        B::Rel(l, _, r) => mutate_expr(l, target, seen) || mutate_expr(r, target, seen),
        B::And(l, r) | B::Or(l, r) => {
            if *seen == target {
                let lifted = (**l).clone();
                *b = lifted;
                return true;
            }
            *seen += 1;
            if *seen == target {
                let lifted = (**r).clone();
                *b = lifted;
                return true;
            }
            *seen += 1;
            mutate_bool(l, target, seen) || mutate_bool(r, target, seen)
        }
        B::Not(inner) => {
            if *seen == target {
                let lifted = (**inner).clone();
                *b = lifted;
                return true;
            }
            *seen += 1;
            mutate_bool(inner, target, seen)
        }
    }
}

/// The smallest program reachable by repeated one-step simplification that
/// still fails in `form`. Bounded, because each candidate costs a compile and a
/// run and a pathological case should not hang the suite.
fn shrink(p: &Prog, form: Form, kind: Kind) -> Prog {
    const BUDGET: usize = 1500;
    let mut best = p.clone();
    let mut spent = 0usize;
    loop {
        let mut available = 0usize;
        mutate(&mut best.clone(), usize::MAX, &mut available);

        let mut improved = false;
        for k in 0..available {
            if spent >= BUDGET {
                return best;
            }
            let mut cand = best.clone();
            let mut seen = 0usize;
            if !mutate(&mut cand, k, &mut seen) {
                continue;
            }
            spent += 1;
            if disagrees_as(&cand, form).is_some_and(|(k, _)| k == kind) {
                best = cand;
                improved = true;
                break;
            }
        }
        if !improved {
            return best;
        }
    }
}

/// A compile error that is a known, documented limit rather than a defect.
///
/// Argument staging uses a fixed 11-byte zero-page pool, so a call nested in
/// another call's argument list can exhaust it. The generator budgets the pool
/// to keep this rare, but it cannot be exact — the pool has other consumers
/// that a program's source does not reveal — and encoding the compiler's
/// allocator into the generator would be the wrong place for that knowledge.
///
/// The limit fails loudly, names its workaround, has a regression test
/// (`tests/e2e/nested_calls.rs`) and a roadmap entry saying what lifting it
/// takes. Skipping it here keeps the run spent on wrong answers; the count is
/// reported so it cannot quietly become the common case.
fn is_known_limit(why: &str) -> bool {
    why.contains("argument-evaluation pool exhausted")
}

/// One generated case, checked against the oracle in every surface form.
/// `Ok(true)` means the case was skipped as a known limit.
fn check_seed(seed: u64) -> Result<bool, String> {
    let p = gen_program(seed);
    let Some((form, kind, why)) = disagrees(&p) else {
        return Ok(false);
    };
    if is_known_limit(&why) {
        return Ok(true);
    }

    let small = shrink(&p, form, kind);
    let why = disagrees_as(&small, form)
        .map(|(_, why)| why)
        .unwrap_or_else(|| "no longer reproduces".into());
    Err(format!(
        "seed {seed}: {form:?} form {why}\ntype: {}\n--- reduced source ---\n{}",
        small.ty.name(),
        render_program(&small, form)
    ))
}

#[test]
fn generated_programs_compute_what_they_should() {
    // Quiet the default hook: a rejected program is reported by `observe`, and
    // the backtrace spam would bury the failing source.
    let prev = std::panic::take_hook();
    std::panic::set_hook(Box::new(|_| {}));

    let iters = iterations();
    let base: u64 = std::env::var("WRAITH_FUZZ_SEED")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(0);

    let mut failures = Vec::new();
    let mut skipped = 0u64;
    for i in 0..iters {
        match check_seed(base.wrapping_add(i)) {
            Ok(true) => skipped += 1,
            Ok(false) => {}
            Err(e) => {
                failures.push(e);
                // A handful of examples is enough to debug; do not print
                // hundreds.
                if failures.len() >= 3 {
                    break;
                }
            }
        }
    }

    std::panic::set_hook(prev);
    assert!(
        failures.is_empty(),
        "{} of {iters} generated programs were miscompiled:\n\n{}",
        failures.len(),
        failures.join("\n\n========================\n\n")
    );
    // Loud enough to notice, and a hard cap so the search cannot quietly
    // degrade into one that mostly tests the pool limit.
    if skipped > 0 {
        eprintln!(
            "{skipped} of {iters} seeds skipped: argument-staging pool exhausted \
             (a documented limit — see docs/ROADMAP.md)"
        );
    }
    assert!(
        skipped * 20 <= iters.max(20),
        "{skipped} of {iters} seeds hit the argument-staging pool limit; the generator's \
         budget for it has stopped working"
    );
}

