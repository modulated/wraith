#[derive(Clone, Copy, PartialEq, Eq)]
enum Cmp {
    Eq,
    Ne,
    Lt,
    Le,
    Gt,
    Ge,
}

impl Cmp {
    fn sym(self) -> &'static str {
        match self {
            Cmp::Eq => "==",
            Cmp::Ne => "!=",
            Cmp::Lt => "<",
            Cmp::Le => "<=",
            Cmp::Gt => ">",
            Cmp::Ge => ">=",
        }
    }
    fn apply(self, a: i64, b: i64) -> bool {
        match self {
            Cmp::Eq => a == b,
            Cmp::Ne => a != b,
            Cmp::Lt => a < b,
            Cmp::Le => a <= b,
            Cmp::Gt => a > b,
            Cmp::Ge => a >= b,
        }
    }
}

const CMPS: [Cmp; 6] = [Cmp::Eq, Cmp::Ne, Cmp::Lt, Cmp::Le, Cmp::Gt, Cmp::Ge];

/// An expression of the program's one type.
#[derive(Clone)]
enum E {
    Lit(i64),
    /// A variable of the enclosing scope: `v0…` in `main`, `p0…`/`q0…` (a
    /// parameter or a local) inside a generated function.
    Var(usize),
    /// The induction variable of an enclosing `for`, by loop id. It is always
    /// `u8`; at any other program type it appears through a cast. Rendered
    /// `lv{id}` rather than `i{id}` because loop 8 would otherwise be named
    /// `i8`, which is a type name and not an identifier — a parse error the
    /// fuzzer duly reported against itself.
    Loop(usize),
    Bin(Box<E>, Op, Box<E>),
    /// Out to another type and straight back: truncation and sign-extension,
    /// with no mixed-width arithmetic attached.
    Cast(Ty, Box<E>),
    /// An operand at a *boundary* — a binding, an assignment, an argument, or a
    /// `return` — tagged with the type it was generated at.
    ///
    /// A boundary is the only place the two can differ. Where the destination
    /// is the wide half of the pair and this says the narrow half, the language
    /// widens with no syntax at all, so the node renders as nothing and exists
    /// to record where the arithmetic stopped: the operand is computed at the
    /// *narrow* type first, so `200u8 + 100` bound to a `u16` is 44 and not
    /// 300. Where they agree it is a no-op, and still carried, because the
    /// renderer has no other way to know a call argument's type differs from
    /// the type of the expression it sits inside.
    ///
    /// It appears at those four places only. Inside an expression the operands
    /// of an operator have already had to agree — `u8 + u16` is a type error —
    /// so there is nothing for a widening to attach to.
    At(Ty, Box<E>),
    /// A call to a generated function. `budget` is the recursion budget, and is
    /// present exactly when the callee is recursive — which is also what says
    /// whether the call site passes one.
    Call {
        id: usize,
        budget: Option<u32>,
        args: Vec<E>,
        /// Which of `main`'s slices is handed to a slice-taking callee, or
        /// `None` when the callee takes none. A four-byte descriptor staged
        /// alongside the scalar arguments, which is the widest thing the
        /// argument pool ever holds.
        slice_arg: Option<usize>,
        /// Whether `main`'s struct is handed to a struct-taking callee. There
        /// is only one struct in scope, so this is a yes/no where the slice is
        /// an index. Staged as a two-byte *address*, which is a third thing
        /// again: not a value in the registers and not a descriptor copied out
        /// of a slot.
        struct_arg: bool,
        /// The same for `main`'s enum. Two bytes with the high byte in X, like
        /// a pointer — but spelled `Named` like a struct, so only the type
        /// registry tells the two apart, and a call form that decides by shape
        /// alone gets it wrong.
        enum_arg: bool,
        /// The same for `main`'s string. Two bytes in A:X like the enum, but a
        /// third spelling again — `String` rather than `Named` — and the kind
        /// two of the width tables had left out.
        str_arg: bool,
    },
    /// A recursive call from inside the function itself, always at `d - 1` and
    /// never reachable at `d == 0`. Kept as its own node rather than an ordinary
    /// `Call` so termination is a property of the *shape*: there is no way to
    /// write a self-call that does not decrease the budget.
    SelfCall(Box<E>),
    /// A call to the other half of a mutually recursive pair, at `d - 1` and
    /// carrying the partner's id. Its own node for the same reason as
    /// `SelfCall`, and the reason the pair matters: two functions in one
    /// call-graph cycle are one SCC, which is the case frame colouring solves
    /// with Tarjan and which a self-call — a cycle of one — never reaches.
    MutualCall(usize, Box<E>),
    /// The enum's tag as a number: `(e as T)` in `main`, `(ep as T)` inside
    /// the function that takes one. A unit enum's value *is* its variant
    /// index, so the oracle needs nothing but that index.
    EnumVal,
    /// A `match` on the enum that extracts a variant's payload — the half of a
    /// tagged union the tag read cannot reach. Variant 0 is unit and yields a
    /// constant; the rest carry a `u8` and yield `(x as T)`. Which arm runs
    /// discriminates the tag, and the arm that runs extracts the payload, so a
    /// compiler that read the wrong offset or misrouted the tag is caught.
    /// `main` only, where the enum is spelled `e`.
    EnumMatch,
    /// `(t.len as T)`. A length read through the pointer, so it is wrong
    /// whenever the pointer is, and it needs nothing of the literal but its
    /// length.
    StrLen,
    /// `(t[<index>] as T)` — a byte of the string. A `str` is semantically an
    /// array of `char`, so indexing yields a `char` and the cast makes it a
    /// number; the byte lives one past the pointer, after the length prefix,
    /// which is a different address computation from a plain array element.
    ///
    /// `main` only, and pure: the string is immutable ROM data, so unlike a
    /// pointer read there is nothing to alias — the byte is a fact about the
    /// literal, and the oracle reads it straight from [`STRINGS`].
    StrIndex(Ix),
    /// `arr[<index>]`, in `main` only.
    Elem(Ix),
    /// `TBL[<index>]` — a `const` array, which lives in ROM and is reached
    /// through an assembler label rather than a zero-page base. A different
    /// lowering from the local array, and the one with the bug history.
    Konst(Ix),
    /// `*p` — a read through `main`'s pointer, which is a *second name* for
    /// one of its variables. Which one is program state: `S::Repoint` moves
    /// it, so the value this reads is not a property of the declaration.
    ///
    /// `main` only, and pure: the alias is what makes this interesting, and
    /// reading through it changes nothing.
    PtrLoad,
    /// `**pp` — a read through `main`'s pointer-to-pointer, which names `p`.
    /// With one pointer in scope `pp` can only be `&p`, so the value is the
    /// same as `*p`; what differs is the code, a double dereference the
    /// compiler had to be fixed for once already. `main` only, pure.
    PtrPtrLoad,
    /// `s.f{i}`, in `main` only.
    Field(usize),
    /// `s.a[<index>]` — an element of the struct's *array field*, whose bytes
    /// live inline in the struct rather than behind a pointer. The address is
    /// three terms (the struct's base, the field's offset, the scaled index)
    /// where a plain array's is two, and a 16-bit element scales the last one.
    ///
    /// `main` only: reaching it through the by-reference parameter — `xp.a[i]`
    /// — is refused by the compiler, so generating it there would be a
    /// generator bug rather than a test.
    AField(Ix),
    /// `s.n.g{j}` — a scalar field of the struct nested inside the struct. Its
    /// bytes are inline, at the base plus the nested field's offset plus the
    /// scalar's, so this is the two-level chain a compiler that resolved only
    /// one level of `.field` would miscompute. `main` only, read-only.
    NestedField(usize),
    /// `VTBL[<sel>](<arg>)` — a call through a table of function pointers,
    /// indexed at run time. The callee is not known until then, so this is the
    /// path where the compiler stages arguments at a fixed address and where
    /// frame colouring has to keep the caller clear of every candidate rather
    /// than of a named callee. `main` only.
    Dispatch {
        sel: Sel,
        arg: Box<E>,
    },
    /// `DEV.call(<arg>)` — a call through a function pointer held in a struct
    /// field, which is the shape a driver's vtable takes. Which candidate runs
    /// depends on the `Install` statements executed so far, so unlike
    /// `Dispatch` the answer is program state rather than an index. `main`
    /// only.
    DevCall(Box<E>),
    /// `sl{i}[<index>]` — an element read through a slice descriptor, which is
    /// a base pointer and a length rather than storage of its own. `main` only.
    SliceElem(usize, Ix),
    /// `(sl{i}.len as {ty})` — the other half of the descriptor, and the half a
    /// partial copy loses without disturbing any element. `main` only.
    SliceLen(usize),
    /// `GSTATIC` — a read of the mutable `static` in RAM, at the program's base
    /// type. Its value is program state written by [`S::GStore`], so a read
    /// cannot be folded to its initialiser. Unlike a local, it lives at an
    /// absolute BSS address the reset handler initialises. `main` only.
    GLoad,
}

/// Which entry of the function-pointer table a `Dispatch` selects. In range by
/// construction, like [`Ix`], and for the same reason.
#[derive(Clone)]
enum Sel {
    /// A constant, so the callee is knowable at compile time even though the
    /// call is indirect.
    Lit(usize),
    /// `(v{i} as u8) % <candidates>`: genuinely not known until run time.
    Wrapped(usize),
}

/// An array index. Every form is in range by construction: the language does no
/// bounds checking (this is a 6502), so an out-of-range index would read or
/// write storage the oracle does not model, and the disagreement would be the
/// generator's fault rather than the compiler's.
#[derive(Clone)]
enum Ix {
    /// A constant, below the length.
    Lit(usize),
    /// The induction variable of an enclosing `for`. Loop counts never exceed
    /// the array length, so this is always in range — and it is already `u8`,
    /// which is the only type indexing accepts.
    Loop(usize),
    /// `(v{i} as u8) % LEN`: a genuinely computed index. The cast pins it to
    /// `u8` (indexing rejects a 16-bit index) and the modulus pins the range,
    /// whatever the variable holds.
    Wrapped(usize),
}

/// A `match` arm's pattern, at the program's base type. Values are non-negative
/// and within the type; a 16-bit match can carry a bound past 255, which is the
/// range-arm bug's home (a low-byte-only compare would take the wrong arm).
#[derive(Clone, Debug)]
enum MatchPat {
    /// `v =>` — a single value.
    Lit(i64),
    /// `lo..=hi =>` (inclusive) or `lo..hi =>` (exclusive), `lo <= hi`.
    Range(i64, i64, bool),
}

/// Somewhere a value can be stored. Its type decides the assignment's
/// boundary: a narrow expression stored into a wide variable widens.
#[derive(Clone)]
enum Place {
    Var(usize),
    Elem(Ix),
    Field(usize),
    AField(Ix),
}

/// What `main`'s pointer names. A `&T` used to be a second name for a
/// *variable* only; it can equally name a struct field or an array element,
/// and those are different addresses to take — `&s.f0` forces the struct into
/// memory at a field offset, `&arr[k]` is the element-address computation the
/// `memcpy` work had to get right — and different storage to alias. Which one
/// it currently names is program state, moved by [`S::Repoint`], so a read
/// through it is never a fact about the declaration.
///
/// A field or an element target is only ever at the aggregate type, so the
/// pointer is at that type when it may name one; a variable target keeps the
/// old freedom of any of the four types.
#[derive(Clone, PartialEq)]
enum PtrTarget {
    Var(usize),
    Field(usize),
    Elem(usize),
}

impl PtrTarget {
    /// The expression that reads the aliased place directly, under its own
    /// name — for the invalidation follow-up after a store through the pointer.
    fn read(&self) -> E {
        match self {
            PtrTarget::Var(k) => E::Var(*k),
            PtrTarget::Field(k) => E::Field(*k),
            PtrTarget::Elem(k) => E::Elem(Ix::Lit(*k)),
        }
    }
    /// How `&<target>` is written.
    fn addr(&self) -> String {
        match self {
            PtrTarget::Var(k) => format!("&v{k}"),
            PtrTarget::Field(k) => format!("&s.f{k}"),
            PtrTarget::Elem(k) => format!("&arr[{k}]"),
        }
    }
}

/// Elements in the generated array, and the largest `for` count, so a loop
/// variable is always a valid index.
const ALEN: usize = 4;

/// Scalar fields in the generated struct.
const SFIELDS: usize = 2;
/// Elements in the struct's array field.
///
/// Three, not four: a length that differs from [`ALEN`] is what catches an
/// offset computed from the wrong array, and the two scalar fields sit either
/// side of it so a base that is off by a field lands somewhere visible.
const AFLEN: usize = 3;
/// Scalar fields in the struct nested inside the struct — `S.n: Inner`, where
/// `Inner { g0, g1 }`. A struct laid out inside another is inline bytes, so
/// `s.n.g1` is the base plus the nested field's offset plus `g1`'s: a two-level
/// offset a compiler that only knew one level would get wrong.
const NESTED: usize = 2;
/// Variants of the generated unit enum. Three is enough for the tag to be a
/// value rather than a flag, and few enough that the whole range is reachable.
const EVARIANTS: usize = 3;
/// The string literals `main` may hold. Distinct lengths, so a `str` that
/// arrives through a half-written pointer reports a length that is not the
/// right one rather than one that happens to match.
const STRINGS: [&str; 4] = ["a", "bcd", "efghi", "jklmnopq"];

/// A condition. Only ever a condition — `bool` as a *value* has its own
/// widening rule, which is a separate question from control flow.
#[derive(Clone)]
enum B {
    /// A comparison, and the type *both* its operands were generated at. A
    /// comparison is not a boundary — `u8 < u16` is a type error — so the two
    /// sides agree and the type has to be recorded for the oracle to evaluate
    /// them at the same width.
    Rel(Ty, Box<E>, Cmp, Box<E>),
    And(Box<B>, Box<B>),
    Or(Box<B>, Box<B>),
    Not(Box<B>),
}

#[derive(Clone)]
enum S {
    /// A store, the type of its destination, and the value. The type is what
    /// the value renders and evaluates at — a `Widen` inside it says the
    /// arithmetic happened narrower — and it is not the enclosing scope's:
    /// `main` renders at the aggregate type, and its variables are a mix.
    Assign(Place, Ty, E),
    If(B, Vec<S>, Option<Vec<S>>),
    /// `for i{id} in 0..{count}`.
    For(usize, u32, Vec<S>),
    /// `while c{id} > 0 { … c{id} = c{id} - 1; }`. The counter is declared at
    /// the top with a positive start value and is written by nothing else, so
    /// the loop terminates by construction.
    While(usize, Vec<S>),
    /// `DEV.call = f{id};` — install a different driver. The point of the
    /// whole arrangement: what `DevCall` reaches is decided at run time by a
    /// store, not by anything a call graph can see. Carries the function's id
    /// rather than its table index, so rendering needs no lookup.
    Install(usize),
    /// `sl{d} = sl{s};` — a descriptor copy between two slices. Four bytes with
    /// no expression anywhere in the source to say so, which is how a version
    /// that copied one of them went unnoticed.
    CopySlice(usize, usize),
    /// `sl{i} = TBL[{start}..{end}];` — build a fresh descriptor over a
    /// different range, so a slice's base and length are program state rather
    /// than a property of its declaration.
    Reslice(usize, usize, usize),
    /// `sl{i} = mk({k});` — a descriptor that arrives from a *call*, which
    /// returns a pointer to it in A:X rather than the four bytes themselves.
    /// A different path again from either of the two above.
    SliceFromCall(usize, usize),
    /// `*p = <expr>;` — a store through the pointer, which lands in whichever
    /// variable it currently names. The other half of the alias: a value
    /// written under one name has to be visible under the other, and a
    /// compiler that kept the variable in a register across the store would
    /// answer with the stale one.
    PtrStore(Ty, E),
    /// `**pp = <expr>;` — a store through the pointer-to-pointer, landing in
    /// whatever `p` names now. The double-dereference store, the write half of
    /// [`E::PtrPtrLoad`].
    PtrPtrStore(Ty, E),
    /// `p = &v{k};` — the alias moved to another variable of the same type.
    /// What makes the pointer's target program state rather than a fact about
    /// the declaration, so a read through it cannot be folded away.
    Repoint(PtrTarget),
    /// `v{dst} = pk(&s, <expr>);` — a call that takes `main`'s struct **by
    /// pointer**, writes one of its fields, and returns another.
    ///
    /// This is the aggregate half of the alias: the callee's storage and the
    /// caller's are the same bytes, so a write inside `pk` has to be visible
    /// in `main` afterwards, and the value that comes back is read from those
    /// same bytes. A `&S` parameter that copied instead of pointing would
    /// answer both correctly *inside* the callee and leave `main`'s struct
    /// untouched — which no expression-level check would notice.
    ///
    /// A statement rather than an expression because it has a side effect on
    /// `main`'s state, and the oracle evaluates expressions without one.
    PokeStruct(usize, E),
    /// `v{dst} = bp(&v{target}, <expr>);` — a call that takes one of `main`'s
    /// variables **by pointer**, adds to it through the pointer, and returns
    /// the new value. The scalar analogue of `PokeStruct`: the callee's `*pp`
    /// and the caller's `v{target}` are the same byte(s), so the write inside
    /// `bp` has to show up in `main` afterwards. A `&T` parameter that copied
    /// instead of pointing would answer the return correctly and leave
    /// `v{target}` untouched — which is why `target` and `dst` are read as two
    /// separate cells in the output.
    PokePtr(usize, usize, E),
    /// `s = mks({k});` — the whole struct replaced by one that arrives from a
    /// *call*, which returns a pointer to its bytes in A:X and leaves the
    /// caller to copy them out.
    ///
    /// Two shapes behind the one statement, chosen by `k`: `mks(0)` returns a
    /// constant literal, which is ROM data reached by label, and `mks(1)`
    /// returns a local, which is frame storage reached by its address. Those
    /// are different code in the callee — and returning the local is what used
    /// to load the struct's *first byte* into A and leave X holding whatever
    /// the last instruction did.
    StructFromCall(usize),
    /// `memcpy(&arr[{dst}], &TBL[{src}], {len});` — a run of bytes moved from
    /// the `const` table into the local array.
    ///
    /// This is what replaces whole-array assignment, which is refused: an array
    /// is initialised once and copied explicitly thereafter. It also exercises
    /// two address computations that have their own bug history — `&arr[i]`
    /// into a BSS array, and `&TBL[i]` into a `const` array reached by label —
    /// and does it through a three-argument stdlib call.
    ///
    /// Only for a `u8` aggregate type: `memcpy` takes `&u8` and a *byte* count,
    /// so a 16-bit element would need both a doubled length and a cast, and an
    /// `i8` one would need the address converted — neither is what this is
    /// testing.
    CopyRange {
        dst: usize,
        src: usize,
        len: usize,
    },
    /// `GSTATIC = <expr>;` — a store to the mutable `static` in RAM. The value
    /// is base-typed and may itself read the static ([`E::GLoad`]), so this is a
    /// read-modify-write to an absolute BSS address — the store, the INC/DEC
    /// fast path and the A:Y-shuffle fusion all against `$04xx` rather than a
    /// zero-page frame slot. `main` only.
    GStore(E),
    /// `match <scrut> { pat => { … } … _ => { … } }` on an integer, in `main`.
    /// A dispatch the compiler lowers to a comparison chain — literal arms and
    /// range arms, the latter width-correct only if it compares the whole
    /// scrutinee and not just its low byte. The scrutinee and every pattern are
    /// at the base type; arms are disjoint and a wildcard covers the rest.
    IntMatch {
        scrut: E,
        arms: Vec<(MatchPat, Vec<S>)>,
        default: Vec<S>,
    },
}

/// Variables in `main`.
const VARS: usize = 4;

/// Slices of the `const` table a program declares when it declares any.
///
/// Two, because one slice cannot be copied into another and copying is the
/// operation with the history. They view a *`const`* table: it lives in ROM and
/// nothing writes it, so the oracle needs the descriptor's two numbers and
/// nothing about aliasing.
const SLICES: usize = 2;

/// A generated function. Its body reads only its own parameters and locals, so
/// a call is a pure function of its arguments and the oracle can evaluate it
/// without modelling aliasing or evaluation order.
#[derive(Clone)]
struct Func {
    /// Parameters, not counting a recursive function's depth budget.
    params: usize,
    /// The type of each parameter, then of each local, in the order `Scope::var`
    /// resolves them. A scope holds a mix, which is the point: an expression
    /// can only name a variable of the type it is being generated at.
    var_types: Vec<Ty>,
    /// What the function returns. A `return` widens to it implicitly when the
    /// expression is the narrow half of the pair.
    ret_ty: Ty,
    /// Whether a leading `sp: &[T]` parameter carries a slice in. Only ever set
    /// on `f0`, which no other function can call — the call graph runs from low
    /// to high — so the only caller is `main`, and `main` is the only scope
    /// that has a slice to hand over.
    slice_param: bool,
    /// Whether a leading `xp: S` parameter carries `main`'s struct in, by
    /// address. Set under the same conditions as `slice_param` and on the same
    /// function, so a program can hand over both at once — which is the case
    /// that put two wide parameters in one staging block and shifted every
    /// value after them.
    struct_param: bool,
    /// Whether a leading `ep: C` parameter carries `main`'s enum in. Chosen
    /// independently of the other two, so a program takes any subset of the
    /// three — which keeps the argument pool from being loaded to its limit in
    /// every program while still reaching the case where it is.
    enum_param: bool,
    /// Whether a leading `tp: str` parameter carries `main`'s string in.
    str_param: bool,
    /// The other half of the mutually recursive pair, when this function is
    /// one of them. Both members are `recursive`, and the shrinker needs the
    /// link: dissolving one without the other leaves a call to a function that
    /// no longer takes a budget.
    partner: Option<usize>,
    /// Initial values of the locals declared at the top of the body.
    local_init: Vec<i64>,
    recursive: bool,
    /// Statements before the final `return`.
    body: Vec<S>,
    /// The returned expression. For a recursive function this is where the
    /// self-call lives, so the recursion is always reached and always at a
    /// smaller budget.
    ret: E,
    /// What a recursive function returns at `d == 0`. Never contains a
    /// self-call — that is what makes the base case a base case.
    base: E,
}

/// What a call site needs to know about a callee it has not seen generated.
#[derive(Clone)]
struct Sig {
    params: Vec<Ty>,
    ret: Ty,
    recursive: bool,
}

/// Which names `E::Var` resolves to, and which function a self-call names.
#[derive(Clone, Copy)]
enum Scope {
    Main,
    Func {
        id: usize,
        params: usize,
        /// Whether this function carries a slice, which a self-call has to
        /// pass along and which `sp` names.
        slice: bool,
        /// The same for the struct, which `xp` names.
        has_struct: bool,
        /// And for the enum, which `ep` names.
        has_enum: bool,
        /// And for the string, which `tp` names.
        has_str: bool,
    },
}

impl Scope {
    fn var(self, i: usize) -> String {
        match self {
            Scope::Main => format!("v{i}"),
            Scope::Func { params, .. } if i < params => format!("p{i}"),
            Scope::Func { params, .. } => format!("q{}", i - params), // local
        }
    }
}

