    fn repo(rel: &str) -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join(rel)
    }

    /// The variants of `pub enum {name}` in a source file, in declaration
    /// order. Reading them from the source is what makes a newly added
    /// construct show up here instead of being quietly absent.
    fn variants_of(file: &str, name: &str) -> Vec<String> {
        let text = std::fs::read_to_string(repo(file)).expect("AST source is readable");
        let head = format!("pub enum {name} {{");
        let start = text
            .find(&head)
            .unwrap_or_else(|| panic!("{file} no longer declares `{head}`"))
            + head.len();
        let body = &text[start..];
        let end = body
            .find("\n}")
            .unwrap_or_else(|| panic!("unterminated `pub enum {name}` in {file}"));

        let mut out = Vec::new();
        for line in body[..end].lines() {
            // A variant sits at one level of indentation and starts with a
            // capital; doc comments, attributes and field lines do not.
            let Some(rest) = line.strip_prefix("    ") else {
                continue;
            };
            if rest.starts_with(' ') || !rest.starts_with(|c: char| c.is_ascii_uppercase()) {
                continue;
            }
            let ident: String = rest
                .chars()
                .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
                .collect();
            let after = rest[ident.len()..].trim_start();
            if after.starts_with(',') || after.starts_with('(') || after.starts_with('{') {
                out.push(ident);
            }
        }
        assert!(
            out.len() >= 4,
            "extracted only {out:?} from `pub enum {name}` in {file} — the parse is wrong, \
             not the enum"
        );
        out
    }

