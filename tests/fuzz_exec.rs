    /// How many of the sampled programs contain each construct.
    fn tally() -> BTreeMap<String, usize> {
        let mut counts: BTreeMap<String, usize> = BTreeMap::new();
        for seed in 0..SAMPLE {
            let p = gen_program(seed);
            // One program per seed, but every surface form of it: the `match`
            // arm and the called function are part of what gets compiled.
            let mut seen = Seen::new();
            for form in FORMS {
                let src = render_program(&p, form);
                let tokens = wraith::lex(&src).expect("generated source lexes");
                let file = wraith::parser::Parser::parse(&tokens).expect("generated source parses");
                for item in &file.items {
                    w_item(&item.node, &mut seen);
                }
            }
            for k in seen {
                *counts.entry(k).or_default() += 1;
            }
        }
        counts
    }

    fn render(counts: &BTreeMap<String, usize>) -> String {
        let reasons: BTreeMap<&str, &str> = REASONS.iter().copied().collect();
        let caveats: BTreeMap<&str, &str> = CAVEATS.iter().copied().collect();
        let mut out = String::new();
        out.push_str(
            "# What the execution-checked fuzzer covers\n\n\
             Generated by `tests/fuzz_exec.rs`; do not edit by hand. Regenerate with:\n\n\
             ```text\n\
             WRAITH_BLESS_FUZZ_COVERAGE=1 cargo test --test fuzz_exec coverage\n\
             ```\n\n",
        );
        out.push_str(&format!(
            "Every construct in the language's AST is listed. **Programs** is how many of \
             {SAMPLE} generated programs contain it, counted by parsing the emitted source and \
             walking the real AST — so the scaffolding each program needs is counted too, not \
             just the part the generator models. Where a construct is generated, the note says \
             what is *not* varied within it; where it is not generated, the note says why, \
             because \"not covered\" should be a decision on the record rather than an \
             omission.\n\n\
             The variant lists are read from `src/ast/*.rs` at test time, so a construct added \
             to the language shows up here as uncovered rather than going unmentioned.\n\n"
        ));

        for (group, file, heading) in GROUPS {
            out.push_str(&format!("## {heading}\n\n"));
            out.push_str("| Construct | Programs | Notes |\n|---|---:|---|\n");
            for variant in variants_of(file, group) {
                let key = format!("{group}::{variant}");
                let n = counts.get(&key).copied().unwrap_or(0);
                let cell = if n == 0 {
                    format!(
                        "— | not generated: {}",
                        reasons
                            .get(key.as_str())
                            .copied()
                            .unwrap_or("**UNCLASSIFIED**")
                    )
                } else {
                    format!("{n} | {}", caveats.get(key.as_str()).copied().unwrap_or(""))
                };
                out.push_str(&format!("| `{variant}` | {cell} |\n"));
            }
            out.push('\n');
        }
        out
    }

    fn doc_path() -> PathBuf {
        repo("docs/fuzz-coverage.md")
    }

    /// The document must match what the generator actually produces.
    #[test]
    fn coverage_document_is_current() {
        let text = render(&tally());

        if std::env::var("WRAITH_BLESS_FUZZ_COVERAGE").is_ok() {
            std::fs::write(doc_path(), &text).expect("coverage document is writable");
            eprintln!("blessed docs/fuzz-coverage.md");
            return;
        }

        let existing = std::fs::read_to_string(doc_path()).unwrap_or_default();
        assert_eq!(
            existing.trim_end(),
            text.trim_end(),
            "docs/fuzz-coverage.md is out of date. If the generator changed on purpose, \
             regenerate it so the difference shows up in the diff:\n\
             \x20  WRAITH_BLESS_FUZZ_COVERAGE=1 cargo test --test fuzz_exec coverage"
        );
    }

    /// Every construct the fuzzer does not reach must say why, and every note
    /// must still apply. This is the guard that turns a newly added language
    /// feature into a decision instead of a silent gap.
    #[test]
    fn every_uncovered_construct_has_a_reason() {
        let counts = tally();
        let reasons: BTreeMap<&str, &str> = REASONS.iter().copied().collect();

        let mut missing = Vec::new();
        let mut stale = Vec::new();
        let mut known = BTreeSet::new();

        for (group, file, _) in GROUPS {
            for variant in variants_of(file, group) {
                let key = format!("{group}::{variant}");
                known.insert(key.clone());
                let covered = counts.get(&key).copied().unwrap_or(0) > 0;
                match (covered, reasons.contains_key(key.as_str())) {
                    (false, false) => missing.push(key),
                    (true, true) => stale.push(key),
                    _ => {}
                }
            }
        }

        assert!(
            missing.is_empty(),
            "the fuzzer does not reach these, and nothing says why — add a line to REASONS in \
             tests/fuzz_exec.rs, or widen the generator:\n  {}",
            missing.join("\n  ")
        );
        assert!(
            stale.is_empty(),
            "these are generated now, so their REASONS entry is wrong — delete it, and add a \
             CAVEATS line if the coverage is partial:\n  {}",
            stale.join("\n  ")
        );

        let unknown: Vec<&str> = REASONS
            .iter()
            .chain(CAVEATS.iter())
            .map(|(k, _)| *k)
            .filter(|k| !known.contains(*k))
            .collect();
        assert!(
            unknown.is_empty(),
            "REASONS or CAVEATS names constructs the AST no longer has:\n  {}",
            unknown.join("\n  ")
        );

        // A caveat qualifies something the fuzzer reaches. On a construct it
        // does not reach, the caveat is never shown — which is how a limit gets
        // forgotten.
        let unreachable: Vec<&str> = CAVEATS
            .iter()
            .map(|(k, _)| *k)
            .filter(|k| counts.get(*k).copied().unwrap_or(0) == 0)
            .collect();
        assert!(
            unreachable.is_empty(),
            "CAVEATS qualifies constructs the fuzzer never generates, so the note is never \
             shown:\n  {}",
            unreachable.join("\n  ")
        );
    }
