/// The oracle has to be exercised by the shapes it claims to cover, or a
/// generator change could quietly stop producing them.
#[test]
fn the_generator_covers_what_it_claims() {
    #[derive(Default)]
    struct Seen {
        ops: std::collections::HashSet<&'static str>,
        cmps: std::collections::HashSet<&'static str>,
        stmts: std::collections::HashSet<&'static str>,
        bools: std::collections::HashSet<&'static str>,
        types: std::collections::HashSet<&'static str>,
        casts: usize,
        loop_vars: usize,
        calls: usize,
        self_calls: usize,
        multi_arg_calls: usize,
    }

    fn walk_e(e: &E, s: &mut Seen) {
        match e {
            E::Bin(l, op, r) => {
                s.ops.insert(op.sym());
                walk_e(l, s);
                walk_e(r, s);
            }
            E::Cast(_, inner) => {
                s.casts += 1;
                walk_e(inner, s);
            }
            E::Loop(_) => s.loop_vars += 1,
            E::Call { args, .. } => {
                s.calls += 1;
                if args.len() > 1 {
                    s.multi_arg_calls += 1;
                }
                for a in args {
                    walk_e(a, s);
                }
            }
            E::SelfCall(arg) => {
                s.self_calls += 1;
                walk_e(arg, s);
            }
            _ => {}
        }
    }
    fn walk_b(b: &B, s: &mut Seen) {
        match b {
            B::Rel(l, c, r) => {
                s.cmps.insert(c.sym());
                walk_e(l, s);
                walk_e(r, s);
            }
            B::And(l, r) => {
                s.bools.insert("&&");
                walk_b(l, s);
                walk_b(r, s);
            }
            B::Or(l, r) => {
                s.bools.insert("||");
                walk_b(l, s);
                walk_b(r, s);
            }
            B::Not(i) => {
                s.bools.insert("!");
                walk_b(i, s);
            }
        }
    }
    fn walk_s(stmts: &[S], s: &mut Seen) {
        for st in stmts {
            match st {
                S::Assign(_, e) => {
                    s.stmts.insert("assign");
                    walk_e(e, s);
                }
                S::If(c, t, e) => {
                    s.stmts.insert(if e.is_some() { "if-else" } else { "if" });
                    walk_b(c, s);
                    walk_s(t, s);
                    if let Some(e) = e {
                        walk_s(e, s);
                    }
                }
                S::For(_, _, b) => {
                    s.stmts.insert("for");
                    walk_s(b, s);
                }
                S::While(_, b) => {
                    s.stmts.insert("while");
                    walk_s(b, s);
                }
            }
        }
    }

    let mut seen = Seen::default();
    for seed in 0..400u64 {
        let p = gen_program(seed);
        seen.types.insert(p.ty.name());
        walk_s(&p.stmts, &mut seen);
        for f in &p.funcs {
            walk_s(&f.body, &mut seen);
            walk_e(&f.ret, &mut seen);
            walk_e(&f.base, &mut seen);
        }
    }

    for op in OPS {
        assert!(seen.ops.contains(op.sym()), "never emitted `{}`", op.sym());
    }
    for c in CMPS {
        assert!(seen.cmps.contains(c.sym()), "never emitted `{}`", c.sym());
    }
    for k in ["assign", "if", "if-else", "for", "while"] {
        assert!(seen.stmts.contains(k), "never emitted a `{k}` statement");
    }
    for k in ["&&", "||", "!"] {
        assert!(seen.bools.contains(k), "never emitted `{k}`");
    }
    for t in TYPES {
        assert!(seen.types.contains(t.name()), "never used `{}`", t.name());
    }
    assert!(seen.casts > 0, "never emitted a cast");
    assert!(seen.loop_vars > 0, "never read a loop variable");
    assert!(seen.calls > 0, "never emitted a call");
    assert!(
        seen.multi_arg_calls > 0,
        "never emitted a call with more than one argument — the shape where \
         argument staging goes wrong"
    );
    assert!(seen.self_calls > 0, "never emitted a recursive call");
}

/// No name the generator invents may be a reserved word.
///
/// The parse check below would find this only if a random program happened to
/// need nine loops, which took 3046 seeds and two minutes; the rule is about
/// the naming scheme, so it is checked directly and over the whole range of ids
/// any program could reach.
#[test]
fn generated_names_are_never_reserved() {
    // Type names first — the ones a numeric suffix can collide with — then the
    // keywords, so a future prefix cannot land on one of those either.
    const RESERVED: &[&str] = &[
        "u8", "i8", "u16", "i16", "b8", "b16", "bool", "char", "addr", "str", "void", "let", "if",
        "else", "while", "for", "loop", "match", "fn", "struct", "enum", "const", "static",
        "import", "return", "break", "continue", "asm", "pub", "as", "in", "true", "false",
    ];

    let mut names: Vec<String> = vec![
        "arr".into(),
        "s".into(),
        "d".into(),
        "sel".into(),
        "w0".into(),
        "body".into(),
        "main".into(),
        "TBL".into(),
        "S".into(),
    ];
    for id in 0..64usize {
        names.push(loop_var(id));
        names.push(format!("c{id}"));
        names.push(format!("f{id}"));
        names.push(format!("o{id}"));
        names.push(format!("OUT{id}"));
        names.push(Scope::Main.var(id));
        names.push(Scope::Func { id: 0, params: 2 }.var(id));
    }

    for name in &names {
        assert!(
            !RESERVED.contains(&name.as_str()),
            "the generator can produce the name `{name}`, which is reserved"
        );
    }
}

/// Every generated program must at least *parse*, in every surface form.
///
/// Cheap enough to run over far more seeds than the execution check, and it
/// catches the mistakes that are the generator's rather than the compiler's —
/// a name that collides with a keyword, a malformed construct — in
/// milliseconds instead of after a hundred seconds of compiling and emulating.
/// Loop variables were named `i{id}`, so a program with nine loops declared
/// `i8`, and that is what found it.
#[test]
fn every_generated_program_parses() {
    for seed in 0..2000u64 {
        let p = gen_program(seed);
        for form in FORMS {
            let src = render_program(&p, form);
            let tokens = match wraith::lex(&src) {
                Ok(t) => t,
                Err(e) => panic!("seed {seed} {form:?} does not lex: {e:?}\n{src}"),
            };
            if let Err(e) = wraith::parser::Parser::parse(&tokens) {
                panic!("seed {seed} {form:?} does not parse: {e:?}\n{src}");
            }
        }
    }
}

/// The oracle's own arithmetic, pinned against hand-checked values. If this
/// drifts, every "miscompile" it reports is suspect.
#[test]
fn the_oracle_matches_the_documented_semantics() {
    let cases: &[(Ty, i64, Op, i64, i64)] = &[
        // Wrapping, both directions.
        (Ty::U8, 200, Op::Add, 100, 44),
        (Ty::I8, -100, Op::Sub, 100, 56),
        (Ty::U16, 65535, Op::Add, 2, 1),
        // Signed division truncates toward zero; `%` follows the dividend.
        (Ty::I8, -7, Op::Div, 2, -3),
        (Ty::I8, -7, Op::Rem, 2, -1),
        (Ty::I16, -3, Op::Div, 4, 0),
        // `>>` is arithmetic on a signed type, logical on an unsigned one.
        (Ty::I8, -8, Op::Shr, 1, -4),
        (Ty::U8, 255, Op::Shr, 1, 127),
        // `<<` wraps like any other arithmetic.
        (Ty::I8, 100, Op::Shl, 1, -56),
        // Bitwise operators see the bit pattern, not the signed value.
        (Ty::I8, -1, Op::And, 15, 15),
        (Ty::I8, -128, Op::Xor, -128, 0),
    ];
    let empty = Prog {
        ty: Ty::U8,
        init: [0; VARS],
        counters: Vec::new(),
        stmts: Vec::new(),
        loops: 0,
        funcs: Vec::new(),
        aggregates: false,
        arr_init: [0; ALEN],
        field_init: [0; SFIELDS],
        konst: [0; ALEN],
    };
    let st = St {
        prog: &empty,
        vars: vec![0; VARS],
        arr: Vec::new(),
        fields: Vec::new(),
        counters: Vec::new(),
        loops: Vec::new(),
        current: None,
    };
    for (ty, a, op, b, want) in cases {
        let e = E::Bin(Box::new(E::Lit(*a)), *op, Box::new(E::Lit(*b)));
        assert_eq!(
            eval(&e, &st, *ty),
            *want,
            "{} {} {} at {}",
            a,
            op.sym(),
            b,
            ty.name()
        );
    }
}

// ---------------------------------------------------------------------------
// Coverage manifest
// ---------------------------------------------------------------------------
//
// A fuzzer is only as trustworthy as the reader's picture of what it reaches,
// and prose in a module doc goes stale the moment the generator changes. So the
// picture is generated instead: `docs/fuzz-coverage.md` lists every construct in
// the language's AST and says, for each, how many of a fixed sample of programs
// contain it — or, where it is not generated, why not.
//
// Three guards keep it honest:
//
// - The counts come from **parsing the generated programs with the real parser**
//   and walking the real AST, so the scaffolding counts too and nothing is
//   credited from memory.
// - The walkers are **exhaustive matches**, so a new AST variant is a compile
//   error here before it is a missing line in the document.
// - The variant lists are read from **`src/ast/*.rs` at test time**, so a new
//   construct appears in the document as uncovered rather than going
//   unmentioned, and must be given a reason before the suite passes again.
//
// Regenerate with:
//
