/// The name of a `for` induction variable.
///
/// `lv` rather than `i`, because `i8` and `i16` are type names and not
/// identifiers: a program with nine loops declared `for i8 in …`, which the
/// parser rejected. Every site that names a loop variable goes through here so
/// the rule has one place to hold.
fn loop_var(id: usize) -> String {
    format!("lv{id}")
}

fn render_index(ix: &Ix) -> String {
    match ix {
        Ix::Lit(k) => format!("{k}"),
        Ix::Loop(id) => loop_var(*id),
        Ix::Wrapped(i) => format!("((v{i} as u8) % {ALEN})"),
    }
}

fn render_place(p: &Place, sc: Scope) -> String {
    match p {
        Place::Var(v) => sc.var(*v),
        Place::Elem(ix) => format!("arr[{}]", render_index(ix)),
        Place::Field(f) => format!("s.f{f}"),
    }
}

fn render(e: &E, ty: Ty, sc: Scope) -> String {
    match e {
        E::Lit(v) if *v < 0 => format!("({v})"),
        E::Lit(v) => format!("{v}"),
        E::Var(i) => sc.var(*i),
        E::Loop(id) if ty == Ty::U8 => loop_var(*id),
        E::Loop(id) => format!("({} as {})", loop_var(*id), ty.name()),
        E::Bin(l, op, r) => format!("({} {} {})", render(l, ty, sc), op.sym(), render(r, ty, sc)),
        E::Cast(to, inner) => format!(
            "(({} as {}) as {})",
            render(inner, ty, sc),
            to.name(),
            ty.name()
        ),
        E::Call {
            id,
            budget,
            args,
            slice_arg,
            struct_arg,
            enum_arg,
            str_arg,
        } => {
            let mut parts: Vec<String> = Vec::new();
            if let Some(b) = budget {
                parts.push(b.to_string());
            }
            // The descriptor goes after the budget and before the values, in
            // the order `render_func` declares the parameters.
            if let Some(k) = slice_arg {
                parts.push(format!("sl{k}"));
            }
            // Then the struct, by name — the caller hands over a place and the
            // callee takes its address.
            if *struct_arg {
                parts.push(struct_name(sc));
            }
            // Then the enum, in the order `render_func` declares them.
            if *enum_arg {
                parts.push(enum_name(sc));
            }
            if *str_arg {
                parts.push(str_name(sc));
            }
            parts.extend(args.iter().map(|a| render(a, ty, sc)));
            format!("f{id}({})", parts.join(", "))
        }
        E::SelfCall(arg) => {
            let Scope::Func {
                id,
                slice,
                has_struct,
                has_enum,
                has_str,
                ..
            } = sc
            else {
                unreachable!("a self-call outside a function")
            };
            // A recursive function that took a slice hands the same one down;
            // there is nothing else in scope it could pass.
            let sl = if slice { "sp, " } else { "" };
            let xs = if has_struct { "xp, " } else { "" };
            let es = if has_enum { "ep, " } else { "" };
            let ts = if has_str { "tp, " } else { "" };
            format!("f{id}(d - 1, {sl}{xs}{es}{ts}{})", render(arg, ty, sc))
        }
        // The partner's budget is this frame's, one lower. A pair member takes
        // no slice, so there is none to pass.
        E::MutualCall(partner, arg) => format!("f{partner}(d - 1, {})", render(arg, ty, sc)),
        E::Elem(ix) => format!("arr[{}]", render_index(ix)),
        E::Konst(ix) => format!("TBL[{}]", render_index(ix)),
        E::Field(f) => format!("{}.f{f}", struct_name(sc)),
        E::EnumVal => format!("({} as {})", enum_name(sc), ty.name()),
        E::StrLen => format!("({}.len as {})", str_name(sc), ty.name()),
        E::Dispatch { sel, arg } => {
            format!("VTBL[{}]({})", render_sel(sel), render(arg, ty, sc))
        }
        E::DevCall(arg) => format!("DEV.call({})", render(arg, ty, sc)),
        E::SliceElem(i, ix) => {
            let n = slice_name(*i, sc);
            format!("{n}[{}]", render_slice_index(&n, ix, sc))
        }
        E::SliceLen(i) => format!("({}.len as {})", slice_name(*i, sc), ty.name()),
        // No syntax of its own: where this narrows the type, the widening back
        // is what the language does by itself.
        E::At(from, inner) => render(inner, *from, sc),
    }
}

/// Which slice a slice expression names. `main` has `SLICES` of them; a
/// function has exactly one, its parameter, so the index is not consulted.
fn slice_name(i: usize, sc: Scope) -> String {
    match sc {
        Scope::Main => format!("sl{i}"),
        Scope::Func { .. } => "sp".to_string(),
    }
}

/// What the struct is called here. `main` declares `s`; the function that takes
/// one calls it `xp`, and the same `E::Field` node reads through whichever is
/// in scope — which is the point of passing it at all.
fn struct_name(sc: Scope) -> String {
    match sc {
        Scope::Main => "s".to_string(),
        Scope::Func { .. } => "xp".to_string(),
    }
}

/// What the enum is called here, on the same rule as the struct.
fn enum_name(sc: Scope) -> String {
    match sc {
        Scope::Main => "e".to_string(),
        Scope::Func { .. } => "ep".to_string(),
    }
}

/// What the string is called here, on the same rule again.
fn str_name(sc: Scope) -> String {
    match sc {
        Scope::Main => "t".to_string(),
        Scope::Func { .. } => "tp".to_string(),
    }
}

/// An index into a slice. The modulus is the slice's *run-time* length, so the
/// source reads it out of the descriptor rather than naming a constant.
fn render_slice_index(name: &str, ix: &Ix, sc: Scope) -> String {
    match ix {
        Ix::Lit(k) => format!("{k}"),
        Ix::Loop(id) => loop_var(*id),
        // Named through the scope: inside a function this is a parameter or a
        // local, not one of `main`'s variables.
        Ix::Wrapped(v) => format!("(({} as u8) % ({name}.len as u8))", sc.var(*v)),
    }
}

/// The table index of a `Dispatch`. `vt` is the number of entries, which the
/// modulus needs and the tree does not carry.
fn render_sel(sel: &Sel) -> String {
    match sel {
        Sel::Lit(k) => format!("{k}"),
        Sel::Wrapped(i) => format!("((v{i} as u8) % VT_LEN)"),
    }
}

fn render_bool(b: &B, sc: Scope) -> String {
    match b {
        B::Rel(at, l, c, r) => format!(
            "({} {} {})",
            render(l, *at, sc),
            c.sym(),
            render(r, *at, sc)
        ),
        B::And(l, r) => format!("({} && {})", render_bool(l, sc), render_bool(r, sc)),
        B::Or(l, r) => format!("({} || {})", render_bool(l, sc), render_bool(r, sc)),
        B::Not(inner) => format!("(!{})", render_bool(inner, sc)),
    }
}

/// Statements no longer render at a scope type: an assignment carries its
/// destination's, and a comparison carries the type its two sides were
/// compared at. What is left threads through to nested blocks only, which is
/// what the lint is pointing at — it is kept so a statement form that *does*
/// need a scope type has somewhere to read one.
#[allow(clippy::only_used_in_recursion)]
fn render_stmts(stmts: &[S], ty: Ty, indent: usize, sc: Scope) -> String {
    let pad = " ".repeat(indent);
    let mut out = String::new();
    for s in stmts {
        match s {
            S::Assign(place, at, e) => out.push_str(&format!(
                "{pad}{} = {};\n",
                render_place(place, sc),
                render(e, *at, sc)
            )),
            S::If(c, then, otherwise) => {
                out.push_str(&format!("{pad}if {} {{\n", render_bool(c, sc)));
                out.push_str(&render_stmts(then, ty, indent + 4, sc));
                match otherwise {
                    Some(e) => {
                        out.push_str(&format!("{pad}}} else {{\n"));
                        out.push_str(&render_stmts(e, ty, indent + 4, sc));
                        out.push_str(&format!("{pad}}}\n"));
                    }
                    None => out.push_str(&format!("{pad}}}\n")),
                }
            }
            S::For(id, count, body) => {
                out.push_str(&format!("{pad}for {} in 0..{count} {{\n", loop_var(*id)));
                out.push_str(&render_stmts(body, ty, indent + 4, sc));
                out.push_str(&format!("{pad}}}\n"));
            }
            S::While(id, body) => {
                out.push_str(&format!("{pad}while c{id} > 0 {{\n"));
                out.push_str(&render_stmts(body, ty, indent + 4, sc));
                out.push_str(&format!("{pad}    c{id} = c{id} - 1;\n"));
                out.push_str(&format!("{pad}}}\n"));
            }
            S::Install(id) => out.push_str(&format!("{pad}DEV.call = f{id};\n")),
            S::CopySlice(d, src) => out.push_str(&format!("{pad}sl{d} = sl{src};\n")),
            S::Reslice(i, start, len) => {
                out.push_str(&format!("{pad}sl{i} = TBL[{start}..{}];\n", start + len))
            }
            S::SliceFromCall(i, k) => out.push_str(&format!("{pad}sl{i} = mk({k});\n")),
        }
    }
    out
}

/// One generated function, declarations and all.
fn render_func(p: &Prog, id: usize) -> String {
    let f = &p.funcs[id];
    // A function works at its own return type; its parameters and locals each
    // have theirs, and the aggregates are not in scope here at all.
    let ty = f.ret_ty;
    let tn = ty.name();
    let sc = Scope::Func {
        id,
        params: f.params,
        slice: f.slice_param,
        has_struct: f.struct_param,
        has_enum: f.enum_param,
        has_str: f.str_param,
    };

    let mut params: Vec<String> = Vec::new();
    if f.recursive {
        params.push("d: u8".to_string());
    }
    // The descriptor comes before the values, so a recursive slice-taking
    // function reads `f0(d - 1, sp, …)` at its self-call.
    // A slice is over the `const` table, so its element type is the aggregate
    // type — not this function's return type, which is its own choice.
    if f.slice_param {
        params.push(format!("sp: &[{}]", p.base.name()));
    }
    // Then the struct, by address. Declared after the descriptor so a function
    // taking both puts four bytes and then two in the staging block, which is
    // the layout that shifted the values after them.
    if f.struct_param {
        params.push("xp: S".to_string());
    }
    // Then the enum, also two bytes by address. Three wide parameters ahead of
    // the values is the heaviest staging block the generator builds.
    if f.enum_param {
        params.push("ep: C".to_string());
    }
    if f.str_param {
        params.push("tp: str".to_string());
    }
    for i in 0..f.params {
        params.push(format!("p{i}: {}", f.var_types[i].name()));
    }

    let mut out = format!("fn f{id}({}) -> {tn} {{\n", params.join(", "));
    for (i, v) in f.local_init.iter().enumerate() {
        let lit = if *v < 0 {
            format!("({v})")
        } else {
            format!("{v}")
        };
        out.push_str(&format!(
            "    let q{i}: {} = {lit};\n",
            f.var_types[f.params + i].name()
        ));
    }
    if f.recursive {
        out.push_str(&format!(
            "    if d == 0 {{ return {}; }}\n",
            render(&f.base, ty, sc)
        ));
    }
    out.push_str(&render_stmts(&f.body, ty, 4, sc));
    out.push_str(&format!("    return {};\n}}\n", render(&f.ret, ty, sc)));
    out
}

/// The surface forms one program is written in. All must agree; each routes
/// through a different part of codegen.
#[derive(Clone, Copy, PartialEq, Debug)]
enum Form {
    /// Statements directly in `main`.
    Inline,
    /// The whole body in a called function.
    ViaFunction,
    /// The statements inside the taken arm of a `match`.
    ViaMatch,
    /// The statements inside a loop that runs exactly once.
    ViaLoop,
}

const FORMS: [Form; 4] = [
    Form::Inline,
    Form::ViaFunction,
    Form::ViaMatch,
    Form::ViaLoop,
];

/// One output byte per 8-bit cell, two per 16-bit one — summed rather than
/// multiplied, since a program's cells no longer share a width.
fn out_bytes(p: &Prog) -> usize {
    cell_types(p)
        .iter()
        .map(|t| if t.wide() { 2 } else { 1 })
        .sum()
}

fn render_program(p: &Prog, form: Form) -> String {
    // `main`'s statements are rendered at the aggregate type: it is what an
    // element or a field reads as, and every expression that is not one
    // carries its own type in the tree.
    let ty = p.base;
    let tn = ty.name();

    let head: String = (0..out_bytes(p))
        .map(|i| format!("const OUT{i}: addr = 0x{:04X};\n", 0x0900 + i))
        .collect();

    // The struct type is declared at the top level, so it exists whether or not
    // this program's `main` uses one.
    let lit = |v: &i64| -> String {
        if *v < 0 {
            format!("({v})")
        } else {
            format!("{v}")
        }
    };
    let enum_decl = if p.enum_init.is_some() {
        let vs: Vec<String> = (0..EVARIANTS).map(|i| format!("C{i}")).collect();
        format!("enum C {{ {} }}\n", vs.join(", "))
    } else {
        String::new()
    };
    let struct_decl = if p.aggregates {
        let fields: Vec<String> = (0..SFIELDS).map(|i| format!("f{i}: {tn}")).collect();
        let table: Vec<String> = p.konst.iter().map(lit).collect();
        format!(
            "struct S {{ {} }}\nconst TBL: [{tn}; {ALEN}] = [{}];\n",
            fields.join(", "),
            table.join(", ")
        )
    } else {
        String::new()
    };

    // Generated functions come before `main` in every surface form: they are
    // what the body calls, and their frames are what the call-graph colouring
    // has to keep apart from it.
    let mut funcs: String = (0..p.funcs.len()).map(|i| render_func(p, i)).collect();

    // `mk` is where a slice arrives from a *call* — a pointer to a descriptor
    // in A:X rather than four bytes in a slot, and a third path again from a
    // range expression or another slice.
    if let [(s0, l0), (s1, l1)] = p.mk_ranges[..] {
        funcs.push_str(&format!(
            "fn mk(k: u8) -> &[{tn}] {{\n             \x20   if k == 0 {{ return TBL[{s0}..{}]; }}\n             \x20   return TBL[{s1}..{}];\n}}\n",
            s0 + l0,
            s1 + l1
        ));
    }

    // The function-pointer table, and the struct field a driver is installed
    // in. Both name the same candidates, and both have to come after the
    // functions they name. Taking their addresses is what makes those
    // functions address-taken, which changes how the whole program is
    // compiled: their arguments arrive through the fixed staging block, and
    // every function that dispatches must be coloured clear of all of them.
    let vtable_decl = if p.vtable > 0 {
        let entries: Vec<String> = (0..p.vtable)
            .map(|k| format!("f{}", p.candidate(k)))
            .collect();
        // The candidates' own signature, which they all share: it is not the
        // aggregate type, and a table declared at the wrong one does not
        // compile.
        let c = &p.funcs[p.candidate(0)];
        let (pt, rt) = (c.var_types[0].name(), c.ret_ty.name());
        format!(
            "const VT_LEN: u8 = {};\n\
struct VT {{ call: fn({pt}) -> {rt} }}\n\
static VTBL: [fn({pt}) -> {rt}; {}] = [{}];\n\
static DEV: VT = VT {{ call: {} }};\n",
            p.vtable,
            p.vtable,
            entries.join(", "),
            entries[0],
        )
    } else {
        String::new()
    };

    let mut decls = String::new();
    for (i, (v, vt)) in p.init.iter().zip(p.var_types.iter()).enumerate() {
        let lit = if *v < 0 {
            format!("({v})")
        } else {
            format!("{v}")
        };
        decls.push_str(&format!("    let v{i}: {} = {lit};\n", vt.name()));
    }
    for (i, c) in p.counters.iter().enumerate() {
        decls.push_str(&format!("    let c{i}: u8 = {c};\n"));
    }
    if p.aggregates {
        let elems: Vec<String> = p.arr_init.iter().map(lit).collect();
        decls.push_str(&format!(
            "    let arr: [{tn}; {ALEN}] = [{}];\n",
            elems.join(", ")
        ));
        let fields: Vec<String> = p
            .field_init
            .iter()
            .enumerate()
            .map(|(i, v)| format!("f{i}: {}", lit(v)))
            .collect();
        decls.push_str(&format!("    let s: S = S {{ {} }};\n", fields.join(", ")));
    }
    if let Some(k) = p.enum_init {
        decls.push_str(&format!("    let e: C = C::C{k};\n"));
    }
    if let Some(k) = p.str_init {
        decls.push_str(&format!("    let t: str = \"{}\";\n", STRINGS[k]));
    }
    for (i, (start, len)) in p.slices.iter().enumerate() {
        decls.push_str(&format!(
            "    let sl{i}: &[{tn}] = TBL[{start}..{}];\n",
            start + len
        ));
    }

    // Every cell is written out, in the order `expected` reports them.
    let mut cells: Vec<String> = (0..VARS).map(|i| format!("v{i}")).collect();
    if p.aggregates {
        cells.extend((0..ALEN).map(|i| format!("arr[{i}]")));
        cells.extend((0..SFIELDS).map(|i| format!("s.f{i}")));
    }
    for i in 0..p.slices.len() {
        cells.push(format!("sl{i}[0]"));
        cells.push(format!("(sl{i}.len as {tn})"));
    }

    // Cells are packed at their own widths, so an output index counts bytes
    // written so far rather than cells.
    let mut stores = String::new();
    let mut out = 0usize;
    for (cell, cty) in cells.iter().zip(cell_types(p)) {
        if cty.wide() {
            let src = if cty.signed() {
                format!("{cell} as u16")
            } else {
                cell.clone()
            };
            stores.push_str(&format!("    let o{out}: u16 = {src};\n"));
            stores.push_str(&format!("    OUT{} = o{out}.low;\n", out));
            stores.push_str(&format!("    OUT{} = o{out}.high;\n", out + 1));
            out += 2;
        } else {
            let src = if cty.signed() {
                format!("{cell} as u8")
            } else {
                cell.clone()
            };
            stores.push_str(&format!("    OUT{out} = {src};\n"));
            out += 1;
        }
    }

    // Re-indent a block of already-formatted statements by one more level.
    let bump = |s: &str| -> String { s.lines().map(|l| format!("    {l}\n")).collect::<String>() };

    let body = render_stmts(&p.stmts, ty, 4, Scope::Main);

    match form {
        Form::Inline => {
            format!(
                "{head}{enum_decl}{struct_decl}{funcs}{vtable_decl}#[reset]\nfn main() {{\n{decls}{body}{stores}    loop {{}}\n}}\n"
            )
        }
        Form::ViaFunction => format!(
            "{head}{enum_decl}{struct_decl}{funcs}{vtable_decl}fn body() {{\n{decls}{body}{stores}}}\n\
             #[reset]\nfn main() {{\n    body();\n    loop {{}}\n}}\n"
        ),
        Form::ViaMatch => format!(
            "{head}{enum_decl}{struct_decl}{funcs}{vtable_decl}#[reset]\nfn main() {{\n{decls}    let sel: u8 = 0;\n\
                 match sel {{\n        0 => {{\n{}{}        }}\n        _ => {{}}\n    }}\n\
             \x20   loop {{}}\n}}\n",
            bump(&bump(&body)),
            bump(&bump(&stores)),
        ),
        Form::ViaLoop => format!(
            "{head}{enum_decl}{struct_decl}{funcs}{vtable_decl}#[reset]\nfn main() {{\n{decls}    for w0 in 0..1 {{\n{}{}    }}\n\
             \x20   loop {{}}\n}}\n",
            bump(&body),
            bump(&stores),
        ),
    }
}

